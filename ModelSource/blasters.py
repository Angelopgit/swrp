def mat_path( name ):
	return f"materials/weapons/{name}.vmat"


def write_materials():
	os.makedirs( MAT_DIR, exist_ok=True )
	for name, ( tint, metal, rough, glow ) in MATERIALS.items():
		lines = ["// Generated by ModelSource/blasters.py", "", "Layer0", "{", '\tshader "shaders/complex.shader"', ""]
		if glow:
			lines.append( "\tF_SELF_ILLUM 1" )
		lines += [
			'\tg_flModelTintAmount "1.000"',
			'\tg_vColorTint "[%.4f %.4f %.4f 0.000000]"' % tint,
			'\tTextureColor "materials/default/default_color.tga"',
			'\tTextureNormal "materials/default/default_normal.tga"',
			'\tTextureRoughness "materials/default/default_rough.tga"',
			'\tTextureAmbientOcclusion "materials/default/default_ao.tga"',
			f'\tg_flMetalness "{metal:.3f}"',
			f'\tg_flRoughnessScaleFactor "{rough:.3f}"',
		]
		if glow:
			lines += [
				'\tg_flSelfIllumAlbedoFactor "0.000"', '\tg_flSelfIllumBrightness "4.000"', '\tg_flSelfIllumScale "1.000"',
				'\tg_vSelfIllumTint "[%.4f %.4f %.4f 0.000000]"' % glow,
				'\tTextureSelfIllumMask "[1.000000 1.000000 1.000000 0.000000]"',
			]
		lines.append( "}" )
		with open( os.path.join( MAT_DIR, name + ".vmat" ), "w", newline="\n" ) as fh:
			fh.write( "\n".join( lines ) + "\n" )


# ---------------------------------------------------------------------------------------------------------------------
# A tiny builder: boxes and cylinders (with optional bevel-ish chamfer) merged into one bmesh with material slots
# ---------------------------------------------------------------------------------------------------------------------

class Gun:
	def __init__( self, name ):
		self.name = name
		self.bm = bmesh.new()
		self.slots = []

	def slot( self, mat ):
		if mat not in self.slots:
			self.slots.append( mat )
		return self.slots.index( mat )

	def _tag( self, geom, mat ):
		idx = self.slot( mat )
		for f in [g for g in geom if isinstance( g, bmesh.types.BMFace )]:
			f.material_index = idx

	def box( self, mat, center, size, rot_y=0.0, taper=None ):
		"""A box; taper=(sx, sz) shrinks the +X end, for sloped noses and stocks."""
		res = bmesh.ops.create_cube( self.bm, size=1.0 )
		verts = res["verts"]
		for v in verts:
			x, y, z = v.co
			if taper and x > 0:
				y *= taper[0]
				z *= taper[1]
			v.co = Vector( ( x * size[0], y * size[1], z * size[2] ) )
		m = Matrix.Translation( Vector( center ) ) @ Matrix.Rotation( math.radians( rot_y ), 4, "Y" )
		bmesh.ops.transform( self.bm, matrix=m, verts=verts )
		faces = list( { f for v in verts for f in v.link_faces } )
		self._tag( faces, mat )

	def cyl( self, mat, start, length, radius, segments=10, axis="X", radius2=None ):
		res = bmesh.ops.create_cone( self.bm, cap_ends=True, cap_tris=False, segments=segments,
			radius1=radius, radius2=radius if radius2 is None else radius2, depth=length )
		verts = res["verts"]
		# cones are built along Z, centred; point them along the axis and move the base to `start`
		rot = { "X": Matrix.Rotation( math.radians( 90 ), 4, "Y" ), "Y": Matrix.Rotation( math.radians( -90 ), 4, "X" ), "Z": Matrix() }[axis]
		off = { "X": Vector( ( length / 2, 0, 0 ) ), "Y": Vector( ( 0, length / 2, 0 ) ), "Z": Vector( ( 0, 0, length / 2 ) ) }[axis]
		m = Matrix.Translation( Vector( start ) + off ) @ rot
		bmesh.ops.transform( self.bm, matrix=m, verts=verts )
		faces = list( { f for v in verts for f in v.link_faces } )
		self._tag( faces, mat )

	def build( self ):
		mesh = bpy.data.meshes.new( self.name )
		self.bm.normal_update()
		self.bm.to_mesh( mesh )
		self.bm.free()
		obj = bpy.data.objects.new( self.name, mesh )
		bpy.context.scene.collection.objects.link( obj )
		for m in self.slots:
			mat = bpy.data.materials.get( mat_path( m ) ) or bpy.data.materials.new( mat_path( m ) )
			obj.data.materials.append( mat )
		return obj


def grip( g, x=0.0, z=0.0, angle=-18.0, h=4.6 ):
	"""Pistol grip whose top sits at (x, z); the origin of every gun is the hand on this grip."""
	g.box( "grip", ( x - 0.6, 0, z - h / 2 ), ( 1.3, 1.1, h ), rot_y=angle )
	g.box( "metal", ( x + 0.9, 0, z - 1.2 ), ( 1.6, 0.3, 0.25 ) )        # trigger guard
	g.box( "metal", ( x + 0.4, 0, z - 0.8 ), ( 0.25, 0.25, 0.9 ) )      # trigger


