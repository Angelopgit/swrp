"""
Original low-poly starships for SWRP's space backdrop, built from primitives (no ripped or downloaded models): a light
fighter, a shuttle and a small frigate. SwrpSpace flies them past the viewports now and then; they are seen thousands of
units away, so they are simple silhouettes with glowing engines and a few lit windows.

    "C:\\Program Files\\Blender Foundation\\Blender 5.2\\blender.exe" -b --factory-startup -P ModelSource/starships.py

Units are s&box units. Each ship points along +X with +Z up and its centre at the origin. Writes
Assets/models/space/ship_<id>_<rev>.fbx (+ .meta, keeps the previous revision), ship_<id>.vmdl and the flat materials in
Assets/materials/starships/.
"""
