PROJECT = os.path.dirname( HERE )
MODEL_DIR = os.path.join( PROJECT, "Assets", "models", "space" )
MAT_DIR = os.path.join( PROJECT, "Assets", "materials", "starships" )
REV = format( int( time.time() ), "x" )[-6:]

# name -> (albedo tint, metalness, roughness, emissive tint or None)
MATERIALS = {
	"hull": ( ( 0.82, 0.82, 0.8 ), 0.2, 0.5, None ),            # pale grey plating
	"hull_dark": ( ( 0.32, 0.33, 0.35 ), 0.5, 0.45, None ),     # panels, intakes, greebles
	"accent": ( ( 0.62, 0.1, 0.08 ), 0.1, 0.5, None ),          # red markings
	"canopy": ( ( 0.05, 0.08, 0.12 ), 0.6, 0.15, None ),        # dark glass
	"engine": ( ( 0.5, 0.75, 1.0 ), 0.0, 0.3, ( 0.45, 0.75, 1.0 ) ),     # thruster glow
	"windows": ( ( 1.0, 0.85, 0.6 ), 0.0, 0.4, ( 1.0, 0.82, 0.55 ) ),   # lit portholes
}


def mat_path( name ):
	return f"materials/starships/{name}.vmat"


def write_materials():
	os.makedirs( MAT_DIR, exist_ok=True )
	for name, ( tint, metal, rough, glow ) in MATERIALS.items():
		lines = ["// Generated by ModelSource/starships.py", "", "Layer0", "{", '\tshader "shaders/complex.shader"', ""]
		if glow:
			lines.append( "\tF_SELF_ILLUM 1" )
		lines += [
			'\tg_flModelTintAmount "1.000"',
			'\tg_vColorTint "[%.4f %.4f %.4f 0.000000]"' % tint,
			'\tTextureColor "materials/default/default_color.tga"',
			'\tTextureNormal "materials/default/default_normal.tga"',
			'\tTextureRoughness "materials/default/default_rough.tga"',
			'\tTextureAmbientOcclusion "materials/default/default_ao.tga"',
			f'\tg_flMetalness "{metal:.3f}"',
			f'\tg_flRoughnessScaleFactor "{rough:.3f}"',
		]
		if glow:
			lines += [
				'\tg_flSelfIllumAlbedoFactor "0.000"', '\tg_flSelfIllumBrightness "8.000"', '\tg_flSelfIllumScale "1.000"',
				'\tg_vSelfIllumTint "[%.4f %.4f %.4f 0.000000]"' % glow,
				'\tTextureSelfIllumMask "[1.000000 1.000000 1.000000 0.000000]"',
			]
		lines.append( "}" )
		with open( os.path.join( MAT_DIR, name + ".vmat" ), "w", newline="\n" ) as fh:
			fh.write( "\n".join( lines ) + "\n" )


class Ship:
	def __init__( self, name ):
		self.name = name
		self.bm = bmesh.new()
		self.slots = []

	def slot( self, mat ):
		if mat not in self.slots:
			self.slots.append( mat )
		return self.slots.index( mat )

	def _tag( self, verts, mat ):
		idx = self.slot( mat )
		for f in { f for v in verts for f in v.link_faces }:
			f.material_index = idx

	def _place( self, verts, center, rot ):
		rx, ry, rz = ( math.radians( a ) for a in rot )
		m = Matrix.Translation( Vector( center ) ) @ Matrix.Rotation( rz, 4, "Z" ) @ Matrix.Rotation( ry, 4, "Y" ) @ Matrix.Rotation( rx, 4, "X" )
		bmesh.ops.transform( self.bm, matrix=m, verts=verts )

	def box( self, mat, center, size, rot=( 0, 0, 0 ), taper=None ):
		"""A box; taper=(sy, sz) shrinks its +X end, for noses and wedges."""
		verts = bmesh.ops.create_cube( self.bm, size=1.0 )["verts"]
		for v in verts:
			x, y, z = v.co
			if taper and x > 0:
				y *= taper[0]
				z *= taper[1]
			v.co = Vector( ( x * size[0], y * size[1], z * size[2] ) )
		self._place( verts, center, rot )
		self._tag( verts, mat )

	def cyl( self, mat, center, length, radius, segments=10, radius2=None, rot=( 0, 0, 0 ) ):
		"""A cylinder along X, centred on `center`."""
		verts = bmesh.ops.create_cone( self.bm, cap_ends=True, cap_tris=False, segments=segments,
			radius1=radius, radius2=radius if radius2 is None else radius2, depth=length )["verts"]
		bmesh.ops.transform( self.bm, matrix=Matrix.Rotation( math.radians( 90 ), 4, "Y" ), verts=verts )
		self._place( verts, center, rot )
		self._tag( verts, mat )

	def build( self ):
		mesh = bpy.data.meshes.new( self.name )
		self.bm.normal_update()
		self.bm.to_mesh( mesh )
		self.bm.free()
		obj = bpy.data.objects.new( self.name, mesh )
		bpy.context.scene.collection.objects.link( obj )
		for m in self.slots:
			obj.data.materials.append( bpy.data.materials.get( mat_path( m ) ) or bpy.data.materials.new( mat_path( m ) ) )
		return obj


def fighter():
	"""A light interceptor about 300 units long: an arrowhead fuselage, swept wings with red tips, twin engines."""
	s = Ship( "ship_fighter" )
	s.box( "hull", ( 20, 0, 0 ), ( 220, 46, 34 ), taper=( 0.25, 0.35 ) )             # fuselage and nose
	s.box( "hull_dark", ( -105, 0, 0 ), ( 40, 52, 36 ) )                            # engine block
	s.box( "canopy", ( 40, 0, 20 ), ( 70, 22, 14 ), taper=( 0.5, 0.4 ) )            # cockpit
	for side in ( 1, -1 ):
		s.box( "hull", ( -45, side * 75, 0 ), ( 90, 110, 6 ), rot=( 0, 0, side * -28 ), taper=( 1.0, 0.6 ) )   # swept wing
		s.box( "accent", ( -75, side * 128, 0 ), ( 40, 12, 7 ), rot=( 0, 0, side * -28 ) )                    # wing tip
		s.box( "hull_dark", ( -60, side * 30, -8 ), ( 70, 10, 10 ) )                                          # wing root intake
		s.cyl( "hull_dark", ( -120, side * 16, 0 ), 34, 13, 10 )                                              # engine bell
		s.cyl( "engine", ( -138, side * 16, 0 ), 4, 11, 10 )                                                  # thruster glow
	s.box( "hull", ( -70, 0, 26 ), ( 50, 5, 34 ), rot=( 0, -20, 0 ) )                # tail fin
	return s.build()


def shuttle():
	"""A boxy transport shuttle about 650 units long with a tall dorsal fin, folded wings and three engines."""
	s = Ship( "ship_shuttle" )
	s.box( "hull", ( 0, 0, 0 ), ( 460, 150, 120 ) )                                   # cabin
	s.box( "hull", ( 270, 0, -10 ), ( 120, 130, 90 ), taper=( 0.55, 0.5 ) )          # nose
	s.box( "canopy", ( 280, 0, 30 ), ( 60, 80, 30 ), taper=( 0.6, 0.4 ) )           # cockpit glazing
	s.box( "hull_dark", ( -260, 0, 0 ), ( 70, 160, 110 ) )                           # engine housing
	for y in ( -50, 0, 50 ):
		s.cyl( "engine", ( -298, y, 0 ), 6, 26, 12 )
	s.box( "hull", ( -40, 0, 170 ), ( 220, 14, 240 ), taper=( 1.0, 0.5 ), rot=( 0, 0, 0 ) )   # dorsal fin
	s.box( "accent", ( -40, 0, 290 ), ( 120, 16, 10 ) )
	for side in ( 1, -1 ):
		s.box( "hull", ( -30, side * 150, -70 ), ( 220, 14, 200 ), rot=( side * 35, 0, 0 ), taper=( 1.0, 0.6 ) )   # folded wing
		for i in range( 5 ):
			s.box( "windows", ( 150 - i * 70, side * 76, 18 ), ( 22, 2, 12 ) )                                   # portholes
	return s.build()


def frigate():
	"""A small escort frigate about 2600 units long: a long wedge hull, a command tower, side sponsons and an engine bank."""
	s = Ship( "ship_frigate" )
	s.box( "hull", ( 200, 0, 0 ), ( 2000, 560, 220 ), taper=( 0.18, 0.45 ) )           # wedge hull
	s.box( "hull_dark", ( -960, 0, 0 ), ( 260, 600, 260 ) )                            # stern block
	s.box( "accent", ( 300, 0, 112 ), ( 1500, 60, 6 ), taper=( 0.3, 1.0 ) )             # dorsal stripe
	s.box( "hull", ( -500, 0, 220 ), ( 360, 160, 240 ), taper=( 0.7, 0.8 ) )            # command tower
	s.box( "hull_dark", ( -460, 0, 360 ), ( 220, 240, 40 ) )                          # bridge deck
	s.box( "windows", ( -350, 0, 362 ), ( 4, 180, 12 ) )                              # bridge windows
	for side in ( 1, -1 ):
		s.box( "hull", ( -500, side * 330, -20 ), ( 700, 140, 150 ) )                   # sponson
		s.cyl( "hull_dark", ( -900, side * 330, -20 ), 120, 60, 12 )
		s.cyl( "engine", ( -962, side * 330, -20 ), 6, 52, 12 )
		for i in range( 12 ):
			s.box( "windows", ( 500 - i * 110, side * ( 250 - i * 18 ), -30 ), ( 30, 2, 10 ), rot=( 0, 0, side * -7 ) )   # portholes
	for z in ( -60, 60 ):
		s.cyl( "engine", ( -1092, 0, z ), 6, 70, 14 )                                    # main thrusters
		s.cyl( "hull_dark", ( -1060, 0, z ), 60, 82, 14 )
	return s.build()


