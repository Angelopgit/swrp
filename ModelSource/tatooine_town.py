def dome_hut( name, r_m, wall_m, dome_m, ochre=False ):
	"""A walk-in domed house: round wall with a doorway facing +X, a dome over it, a step and a vent pipe."""
	p = Piece( name, walk_in=True )
	m = "plaster_ochre" if ochre else "plaster"
	r, wall, dome = r_m * M, wall_m * M, dome_m * M
	p.ring_wall( m, ( 0, 0, 0 ), r, wall, thick=18, door_width=46, door_height=86 )
	p.dome( m, ( 0, 0, wall ), r + 9, dome, inner=True )
	p.box( m, ( r + 16, 0, 4 ), ( 34, 70, 14 ), 4 )                         # doorstep
	p.cyl( "metal_dark", ( -r * 0.4, r * 0.3, wall + dome * 0.75 ), 6, 40 )     # vent
	p.box( m, ( r * 0.75, -r * 0.65, wall * 0.5 ), ( 40, 40, wall ), 6, yaw=40 )  # buttress
	return p


