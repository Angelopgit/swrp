def wall( name, length_m, height_m, curve_deg=0.0 ):
	"""A free-standing adobe wall (cover): straight or bowed, rounded cap, a few holes knocked through."""
	p = Piece( name )
	L, H = length_m * M, height_m * M
	segs = max( 1, int( length_m / 1.5 ) )
	for k in range( segs ):
		t = ( k + 0.5 ) / segs - 0.5
		# bowed: each block turned a little and pushed back along the arc
		x = -abs( t ) ** 2 * L * math.radians( curve_deg )
		p.box( "plaster", ( x, t * L, H / 2 - 15 + ( k % 2 ) * 3 ), ( 20, L / segs + 3, H + 30 ), 5, yaw=curve_deg * t )
	return p


