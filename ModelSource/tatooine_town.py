def write_materials():
	os.makedirs( MAT_DIR, exist_ok=True )
	for name, ( tex, col, metal, rough ) in MATERIALS.items():
		if tex:
			maps = ['\tTextureColor "materials/tatooine/plaster_color.png"', '\tTextureNormal "materials/tatooine/plaster_normal.png"',
				'\tTextureRoughness "materials/tatooine/plaster_rough.png"', '\tTextureAmbientOcclusion "materials/tatooine/plaster_ao.png"']
		else:
			maps = ['\tTextureColor "materials/default/default_color.tga"', '\tTextureNormal "materials/default/default_normal.tga"',
				'\tTextureRoughness "materials/default/default_rough.tga"', '\tTextureAmbientOcclusion "materials/default/default_ao.tga"']
		lines = ["// Generated by ModelSource/tatooine_town.py", "", "Layer0", "{", '\tshader "shaders/complex.shader"', ""] + maps + [
			'\tg_flModelTintAmount "1.000"', '\tg_vColorTint "[%.4f %.4f %.4f 0.000000]"' % col,
			f'\tg_flMetalness "{metal:.3f}"', f'\tg_flRoughnessScaleFactor "{rough:.3f}"', '\tg_bFogEnabled "1"', "}", ""]
		with open( os.path.join( MAT_DIR, name + ".vmat" ), "w", newline="\n" ) as fh:
			fh.write( "\n".join( lines ) )


class Piece:
	def __init__( self, name, walk_in=False, surface="dirt" ):
		self.name, self.walk_in, self.surface = name, walk_in, surface
		self.bm = bmesh.new()
		self.mats = []

	def _mat( self, m ):
		p = f"materials/tatooine/town/{m}.vmat"
		if p not in self.mats: self.mats.append( p )
		return self.mats.index( p )

	def _finish( self, geom_verts, m, bevel=0.0, smooth=False ):
		idx = self._mat( m )
		faces = { f for v in geom_verts for f in v.link_faces }
		for f in faces:
			f.material_index = idx
			f.smooth = smooth
		if bevel > 0:
			edges = list( { e for f in faces for e in f.edges } )
			bmesh.ops.bevel( self.bm, geom=edges, offset=bevel, segments=2, affect="EDGES", profile=0.6, clamp_overlap=True )

	def box( self, m, c, size, bevel=4.0, yaw=0.0 ):
		v = bmesh.ops.create_cube( self.bm, size=1.0 )["verts"]
		bmesh.ops.scale( self.bm, vec=Vector( size ), verts=v )
		if yaw: bmesh.ops.rotate( self.bm, verts=v, cent=Vector(), matrix=Matrix.Rotation( math.radians( yaw ), 3, "Z" ) )
		bmesh.ops.translate( self.bm, vec=Vector( c ), verts=v )
		self._finish( v, m, bevel )

	def cyl( self, m, c, r, depth, segs=20, r2=None, axis="Z", bevel=0.0, smooth=True ):
		v = bmesh.ops.create_cone( self.bm, cap_ends=True, segments=segs, radius1=r, radius2=r if r2 is None else r2, depth=depth )["verts"]
		if axis == "X": bmesh.ops.rotate( self.bm, verts=v, cent=Vector(), matrix=Matrix.Rotation( math.radians( 90 ), 3, "Y" ) )
		if axis == "Y": bmesh.ops.rotate( self.bm, verts=v, cent=Vector(), matrix=Matrix.Rotation( math.radians( 90 ), 3, "X" ) )
		bmesh.ops.translate( self.bm, vec=Vector( c ), verts=v )
		self._finish( v, m, bevel, smooth )

	def dome( self, m, c, r, height, inner=False ):
		"""A hemisphere-ish cap (squashed to `height`), outward faces; inner=True adds the inside surface too."""
		for side in ( ( 1, ), ( 1, -1 ) )[inner]:
			v = bmesh.ops.create_uvsphere( self.bm, u_segments=28, v_segments=14, radius=r if side > 0 else r - 10 )["verts"]
			low = [x for x in v if x.co.z < -0.01]
			bmesh.ops.delete( self.bm, geom=low, context="VERTS" )
			v = [x for x in v if x.is_valid]
			for x in v: x.co.z *= ( height if side > 0 else height - 10 ) / ( r if side > 0 else r - 10 )
			if side < 0:
				bmesh.ops.reverse_faces( self.bm, faces=list( { f for x in v for f in x.link_faces } ) )
			bmesh.ops.translate( self.bm, vec=Vector( c ), verts=v )
			self._finish( v, m, 0.0, True )

	def ring_wall( self, m, c, r, height, thick=16.0, door_deg=0.0, door_width=48.0, door_height=84.0, segs=24 ):
		"""A round wall made of segments; a doorway (gap) facing door_deg with a lintel above it."""
		gap = math.degrees( door_width / r ) if door_width else 0
		step = 360 / segs
		for k in range( segs ):
			a = k * step + step / 2
			d = abs( ( a - door_deg + 180 ) % 360 - 180 )
			chord = 2 * r * math.sin( math.radians( step / 2 ) ) + 4
			ar = math.radians( a )
			pos = ( c[0] + math.cos( ar ) * r, c[1] + math.sin( ar ) * r )
			if door_width and d < gap / 2 + step / 2:
				# lintel over the doorway
				self.box( m, ( pos[0], pos[1], c[2] + ( door_height + height ) / 2 ), ( thick, chord, height - door_height ), 2.0, yaw=a )
				continue
			self.box( m, ( pos[0], pos[1], c[2] + height / 2 - 20 ), ( thick, chord, height + 40 ), 2.0, yaw=a )

	def vault( self, m, c, length, width, height, yaw=0.0 ):
		"""A barrel vault (half cylinder on a low base) along X, rotated by yaw."""
		bm2 = self.bm
		v = bmesh.ops.create_cone( bm2, cap_ends=True, segments=16, radius1=width / 2, radius2=width / 2, depth=length )["verts"]
		bmesh.ops.rotate( bm2, verts=v, cent=Vector(), matrix=Matrix.Rotation( math.radians( 90 ), 3, "Y" ) )
		for x in v:
			if x.co.z < 0: x.co.z = 0
			x.co.z = x.co.z * ( height * 0.45 ) / ( width / 2 ) + height * 0.55
		base = [x for x in v]
		bmesh.ops.rotate( bm2, verts=base, cent=Vector(), matrix=Matrix.Rotation( math.radians( yaw ), 3, "Z" ) )
		bmesh.ops.translate( bm2, vec=Vector( c ), verts=base )
		self._finish( base, m, 0.0, True )
		self.box( m, ( c[0], c[1], c[2] + height * 0.3 - 10 ), ( length, width, height * 0.6 + 20 ), 3.0, yaw=yaw )

	def export( self ):
		bmesh.ops.remove_doubles( self.bm, verts=self.bm.verts[:], dist=0.05 )
		uv = self.bm.loops.layers.uv.verify()
		for f in self.bm.faces:
			n = f.normal
			ax = max( range( 3 ), key=lambda i: abs( n[i] ) )
			for l in f.loops:
				co = l.vert.co
				s = 2 * M      # plaster tiles every 2 m
				l[uv].uv = ( co.x / s, co.y / s ) if ax == 2 else ( co.y / s, co.z / s ) if ax == 0 else ( co.x / s, co.z / s )
		me = bpy.data.meshes.new( self.name )
		self.bm.to_mesh( me )
		self.bm.free()
		ob = bpy.data.objects.new( self.name, me )
		bpy.context.scene.collection.objects.link( ob )
		for p in self.mats:
			ob.data.materials.append( bpy.data.materials.get( p ) or bpy.data.materials.new( p ) )
		bpy.ops.object.select_all( action="DESELECT" )
		ob.select_set( True )
		os.makedirs( OUT, exist_ok=True )
		fbx = f"{self.name}_{REV}"
		bpy.ops.export_scene.fbx( filepath=os.path.join( OUT, fbx + ".fbx" ), use_selection=True, mesh_smooth_type="FACE", axis_forward="Y", axis_up="Z" )
		with open( os.path.join( OUT, fbx + ".fbx.meta" ), "w", newline="\n" ) as fh:
			fh.write( '{\n  "guid": "%s"\n}' % uuid.uuid4() )
		fpath = f"models/tatooine/town/{fbx}.fbx"
		phys = ( MESH if self.walk_in else HULL ) % { "name": self.name, "fbx": fpath, "surface": self.surface }
		with open( os.path.join( OUT, self.name + ".vmdl" ), "w", newline="\n" ) as fh:
			fh.write( VMDL % { "fbx": fpath, "phys": phys } )
		revs = sorted( ( f for f in os.listdir( OUT ) if f.startswith( self.name + "_" ) and f.endswith( ".fbx" ) and len( f ) == len( self.name ) + 11 ), key=lambda f: os.path.getmtime( os.path.join( OUT, f ) ) )
		for old in revs[:-2]:
			for fn in ( old, old + ".meta" ):
				try: os.remove( os.path.join( OUT, fn ) )
				except OSError: pass
		print( "TOWN", self.name, len( me.polygons ), "faces" )
		bpy.data.objects.remove( ob, do_unlink=True )


