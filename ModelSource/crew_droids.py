def export( obj ):
	os.makedirs( MODEL_DIR, exist_ok=True )
	name = obj.name
	fbx = f"{name}_{REV}"
	bpy.ops.object.select_all( action="DESELECT" )
	obj.select_set( True )
	bpy.ops.export_scene.fbx( filepath=os.path.join( MODEL_DIR, fbx + ".fbx" ), use_selection=True, mesh_smooth_type="FACE",
		axis_forward="Y", axis_up="Z" )
	meta = os.path.join( MODEL_DIR, fbx + ".fbx.meta" )
	if not os.path.exists( meta ):
		with open( meta, "w", newline="\n" ) as fh:
			fh.write( '{\n  "guid": "%s"\n}' % uuid.uuid4() )
	with open( os.path.join( MODEL_DIR, name + ".vmdl" ), "w", newline="\n" ) as fh:
		fh.write( VMDL % { "fbx": fbx } )
	revs = sorted( ( f for f in os.listdir( MODEL_DIR ) if f.startswith( name + "_" ) and f.endswith( ".fbx" ) ),
		key=lambda f: os.path.getmtime( os.path.join( MODEL_DIR, f ) ) )
	for old in revs[:-2]:
		for fn in ( old, old + ".meta" ):
			try:
				os.remove( os.path.join( MODEL_DIR, fn ) )
			except OSError:
				pass


NAVY_GREY = ( 0.25, 0.27, 0.32 )


def write_navy_materials():
	"""Grey 'navy fatigues' versions of the clone trooper's materials for the ambient crew: its colour textures greyed
	(white armour to navy grey, dark parts stay dark, no battalion markings), and the crewman model that wears them."""
	import numpy as np
	src = os.path.join( PROJECT, "Assets", "models", "clones", "materials" )
	out_mat = os.path.join( MODEL_DIR, "materials" )
	out_tex = os.path.join( MODEL_DIR, "textures" )
	os.makedirs( out_mat, exist_ok=True )
	os.makedirs( out_tex, exist_ok=True )
	grey = np.array( NAVY_GREY, np.float32 )
	for name in ( "clone_body", "clone_helmet", "clone_gloves" ):
		path = os.path.join( src, name + ".vmat" )
		if not os.path.exists( path ):
			continue
		lines = []
		for line in open( path, encoding="utf-8" ).read().splitlines():
			if "F_TINT_MASK" in line or "TextureTintMask" in line:
				continue
			if line.startswith( "//" ):
				line = "// Generated by ModelSource/crew_droids.py from " + name + ".vmat: navy crew grey."
			if line.strip().startswith( "TextureColor" ):
				tex = line.split( '"' )[1]
				img = bpy.data.images.load( os.path.join( PROJECT, "Assets", *tex.split( "/" ) ) )
				w, h = img.size
				px = np.array( img.pixels[:], np.float32 ).reshape( h, w, 4 )
				lum = ( px[..., :3] @ np.array( [0.3, 0.59, 0.11], np.float32 ) )[..., None]
				px[..., :3] = ( px[..., :3] * 0.25 + lum * 0.75 ) * grey
				img.pixels.foreach_set( px.ravel() )
				img.filepath_raw = os.path.join( out_tex, name + "_navy_color.png" )
				img.file_format = "PNG"
				img.save()
				bpy.data.images.remove( img )
				line = f'\tTextureColor "models/crew/textures/{name}_navy_color.png"'
			lines.append( line )
		with open( os.path.join( out_mat, name + "_navy.vmat" ), "w", newline="\n" ) as fh:
			fh.write( "\n".join( lines ) + "\n" )

	# the crewman model: the clone trooper (with the clone animations) wearing those materials
	drill = os.path.join( PROJECT, "Assets", "models", "clones", "clone_trooper_drill.vmdl" )
	if os.path.exists( drill ):
		text = open( drill, encoding="utf-8" ).read()
		for name in ( "clone_body", "clone_helmet", "clone_gloves" ):
			text = text.replace( f'"models/clones/materials/{name}.vmat"', f'"models/crew/materials/{name}_navy.vmat"' )
		os.makedirs( MODEL_DIR, exist_ok=True )
		with open( os.path.join( MODEL_DIR, "crewman_navy.vmdl" ), "w", newline="\n" ) as fh:
			fh.write( text )


def main():
	bpy.ops.wm.read_factory_settings( use_empty=True )
	write_materials()
	write_navy_materials()
	for build in ( astromech_body, astromech_dome, mouse_droid ):
		obj = build()
		export( obj )
		print( f"CREW {obj.name}: {len( obj.data.polygons )} faces" )


main()
