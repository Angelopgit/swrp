def mat_path( name ):
	return f"materials/crew/{name}.vmat"


def write_materials():
	os.makedirs( MAT_DIR, exist_ok=True )
	for name, ( tint, metal, rough, glow ) in MATERIALS.items():
		lines = ["// Generated by ModelSource/crew_droids.py", "", "Layer0", "{", '\tshader "shaders/complex.shader"', ""]
		if glow:
			lines.append( "\tF_SELF_ILLUM 1" )
		lines += [
			'\tg_flModelTintAmount "1.000"',
			'\tg_vColorTint "[%.4f %.4f %.4f 0.000000]"' % tint,
			'\tTextureColor "materials/default/default_color.tga"',
			'\tTextureNormal "materials/default/default_normal.tga"',
			'\tTextureRoughness "materials/default/default_rough.tga"',
			'\tTextureAmbientOcclusion "materials/default/default_ao.tga"',
			f'\tg_flMetalness "{metal:.3f}"',
			f'\tg_flRoughnessScaleFactor "{rough:.3f}"',
		]
		if glow:
			lines += [
				'\tg_flSelfIllumAlbedoFactor "0.000"', '\tg_flSelfIllumBrightness "5.000"', '\tg_flSelfIllumScale "1.000"',
				'\tg_vSelfIllumTint "[%.4f %.4f %.4f 0.000000]"' % glow,
				'\tTextureSelfIllumMask "[1.000000 1.000000 1.000000 0.000000]"',
			]
		lines.append( "}" )
		with open( os.path.join( MAT_DIR, name + ".vmat" ), "w", newline="\n" ) as fh:
			fh.write( "\n".join( lines ) + "\n" )


class Part:
	def __init__( self, name ):
		self.name = name
		self.bm = bmesh.new()
		self.slots = []

	def slot( self, mat ):
		if mat not in self.slots:
			self.slots.append( mat )
		return self.slots.index( mat )

	def _tag( self, verts, mat ):
		idx = self.slot( mat )
		for f in { f for v in verts for f in v.link_faces }:
			f.material_index = idx

	def _place( self, verts, center, rot ):
		rx, ry, rz = ( math.radians( a ) for a in rot )
		m = Matrix.Translation( Vector( center ) ) @ Matrix.Rotation( rz, 4, "Z" ) @ Matrix.Rotation( ry, 4, "Y" ) @ Matrix.Rotation( rx, 4, "X" )
		bmesh.ops.transform( self.bm, matrix=m, verts=verts )

	def box( self, mat, center, size, rot=( 0, 0, 0 ), taper=None ):
		verts = bmesh.ops.create_cube( self.bm, size=1.0 )["verts"]
		for v in verts:
			x, y, z = v.co
			if taper and z > 0:
				x *= taper[0]
				y *= taper[1]
			v.co = Vector( ( x * size[0], y * size[1], z * size[2] ) )
		self._place( verts, center, rot )
		self._tag( verts, mat )

	def cyl( self, mat, center, height, radius, segments=16, radius2=None, rot=( 0, 0, 0 ) ):
		"""An upright cylinder (along Z) centred on `center`."""
		verts = bmesh.ops.create_cone( self.bm, cap_ends=True, cap_tris=False, segments=segments,
			radius1=radius, radius2=radius if radius2 is None else radius2, depth=height )["verts"]
		self._place( verts, center, rot )
		self._tag( verts, mat )

	def dome( self, mat, center, radius, segments=16, rings=6 ):
		"""The top half of a sphere sitting on `center`."""
		verts = bmesh.ops.create_uvsphere( self.bm, u_segments=segments, v_segments=rings * 2, radius=radius )["verts"]
		for v in verts:
			if v.co.z < 0:
				v.co.z = 0
		self._place( verts, center, ( 0, 0, 0 ) )
		self._tag( verts, mat )

	def build( self ):
		mesh = bpy.data.meshes.new( self.name )
		bmesh.ops.remove_doubles( self.bm, verts=self.bm.verts, dist=0.001 )
		self.bm.normal_update()
		self.bm.to_mesh( mesh )
		self.bm.free()
		obj = bpy.data.objects.new( self.name, mesh )
		bpy.context.scene.collection.objects.link( obj )
		for m in self.slots:
			obj.data.materials.append( bpy.data.materials.get( mat_path( m ) ) or bpy.data.materials.new( mat_path( m ) ) )
		return obj


def astromech_body():
	"""A barrel body on two side legs and a centre foot, about 34 units to the dome ring (the dome is its own model)."""
	p = Part( "astromech_body" )
	p.cyl( "droid_white", ( 0, 0, 22 ), 22, 10.5, 18 )                       # body barrel
	p.cyl( "droid_silver", ( 0, 0, 33.3 ), 0.8, 10.8, 18 )                   # dome ring
	for z in ( 16, 22, 28 ):
		p.box( "droid_panel", ( 10.3, 0, z ), ( 1.0, 5.0, 3.5 ) )            # front panels
	p.box( "droid_grey", ( 10.4, 4.8, 24 ), ( 0.8, 2.0, 10 ) )               # vent strip
	p.box( "droid_lamp", ( 10.6, -4.5, 29 ), ( 0.6, 1.4, 1.4 ) )             # status lamp
	for side in ( 1, -1 ):
		p.box( "droid_white", ( 0, side * 12.5, 20 ), ( 7, 3, 22 ), taper=( 0.8, 1.0 ) )   # leg strut
		p.box( "droid_panel", ( 0, side * 14.1, 24 ), ( 4, 0.4, 8 ) )
		p.cyl( "droid_silver", ( 0, side * 12.5, 30 ), 4, 3.5, 10, rot=( 90, 0, 0 ) )        # shoulder hub
		p.box( "droid_grey", ( 0, side * 12.5, 3 ), ( 12, 5, 6 ), taper=( 0.7, 0.9 ) )        # foot
	p.box( "droid_grey", ( 0, 0, 6 ), ( 8, 6, 8 ), taper=( 0.6, 0.7 ) )        # centre foot
	return p.build()


def astromech_dome():
	"""The turning dome: a silver hemisphere with a sensor eye and panels, origin at the ring."""
