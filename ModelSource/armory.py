"""
Original armory fittings for SWRP, built from primitives (no ripped or downloaded models): a wall-mounted rifle rack
with five cradles (the rifles themselves are the game's DC-15A, hung on it at runtime) and a blaster-cell crate with a
glowing window of charged cells.

    "C:\\Program Files\\Blender Foundation\\Blender 5.2\\blender.exe" -b --factory-startup -P ModelSource/armory.py

Units are s&box units. The rack's back sits on the wall at x = 0 and faces +X, its centre at the origin; the crate stands
on the floor at the origin with its front facing +X. Writes Assets/models/armory/<id>_<rev>.fbx (+ .meta, keeps the
previous revision), <id>.vmdl and flat materials in Assets/materials/armory/.
"""
import os
