import time
import uuid

import bpy
import bmesh
from mathutils import Vector, Matrix

HERE = os.path.dirname( os.path.abspath( __file__ ) )
PROJECT = os.path.dirname( HERE )
MODEL_DIR = os.path.join( PROJECT, "Assets", "models", "armory" )
MAT_DIR = os.path.join( PROJECT, "Assets", "materials", "armory" )
REV = format( int( time.time() ), "x" )[-6:]

# name -> (albedo tint, metalness, roughness, emissive tint or None)
MATERIALS = {
	"armory_frame": ( ( 0.2, 0.21, 0.23 ), 0.6, 0.4, None ),       # gunmetal rack and crate shell
	"armory_plate": ( ( 0.62, 0.63, 0.62 ), 0.3, 0.5, None ),      # pale grey plates
	"armory_red": ( ( 0.55, 0.08, 0.06 ), 0.1, 0.5, None ),        # Republic red stripes
	"armory_rubber": ( ( 0.04, 0.04, 0.045 ), 0.0, 0.85, None ),   # cradle pads, handles
	"armory_glow": ( ( 0.3, 0.6, 1.0 ), 0.0, 0.3, ( 0.3, 0.65, 1.0 ) ),     # charged cells, status lamps
	"armory_amber": ( ( 1.0, 0.7, 0.2 ), 0.0, 0.3, ( 1.0, 0.65, 0.2 ) ),    # rack label lamp
}


def mat_path( name ):
	return f"materials/armory/{name}.vmat"


def write_materials():
	os.makedirs( MAT_DIR, exist_ok=True )
	for name, ( tint, metal, rough, glow ) in MATERIALS.items():
		lines = ["// Generated by ModelSource/armory.py", "", "Layer0", "{", '\tshader "shaders/complex.shader"', ""]
		if glow:
			lines.append( "\tF_SELF_ILLUM 1" )
		lines += [
			'\tg_flModelTintAmount "1.000"',
			'\tg_vColorTint "[%.4f %.4f %.4f 0.000000]"' % tint,
			'\tTextureColor "materials/default/default_color.tga"',
			'\tTextureNormal "materials/default/default_normal.tga"',
			'\tTextureRoughness "materials/default/default_rough.tga"',
			'\tTextureAmbientOcclusion "materials/default/default_ao.tga"',
			f'\tg_flMetalness "{metal:.3f}"',
			f'\tg_flRoughnessScaleFactor "{rough:.3f}"',
		]
		if glow:
			lines += [
				'\tg_flSelfIllumAlbedoFactor "0.000"', '\tg_flSelfIllumBrightness "4.000"', '\tg_flSelfIllumScale "1.000"',
				'\tg_vSelfIllumTint "[%.4f %.4f %.4f 0.000000]"' % glow,
				'\tTextureSelfIllumMask "[1.000000 1.000000 1.000000 0.000000]"',
			]
		lines.append( "}" )
		with open( os.path.join( MAT_DIR, name + ".vmat" ), "w", newline="\n" ) as fh:
			fh.write( "\n".join( lines ) + "\n" )


class Part:
	def __init__( self, name ):
		self.name = name
		self.bm = bmesh.new()
		self.slots = []

	def slot( self, mat ):
		if mat not in self.slots:
			self.slots.append( mat )
		return self.slots.index( mat )

	def box( self, mat, center, size, rot=( 0, 0, 0 ) ):
		verts = bmesh.ops.create_cube( self.bm, size=1.0 )["verts"]
		for v in verts:
			v.co = Vector( ( v.co.x * size[0], v.co.y * size[1], v.co.z * size[2] ) )
		rx, ry, rz = ( math.radians( a ) for a in rot )
		m = Matrix.Translation( Vector( center ) ) @ Matrix.Rotation( rz, 4, "Z" ) @ Matrix.Rotation( ry, 4, "Y" ) @ Matrix.Rotation( rx, 4, "X" )
		bmesh.ops.transform( self.bm, matrix=m, verts=verts )
		idx = self.slot( mat )
		for f in { f for v in verts for f in v.link_faces }:
			f.material_index = idx

	def build( self ):
		mesh = bpy.data.meshes.new( self.name )
		self.bm.normal_update()
		self.bm.to_mesh( mesh )
		self.bm.free()
		obj = bpy.data.objects.new( self.name, mesh )
		bpy.context.scene.collection.objects.link( obj )
		for m in self.slots:
			obj.data.materials.append( bpy.data.materials.get( mat_path( m ) ) or bpy.data.materials.new( mat_path( m ) ) )
		return obj


RACK_WIDTH, RACK_HEIGHT = 132.0, 74.0
CRADLES = 5


def rifle_rack():
	"""A wall rack: a backboard with top and bottom rails, five rubber-padded cradles below and clips above, a red
	stripe and an amber label lamp. Rifles hang upright in it, barrel up, 24 units apart."""
	p = Part( "rifle_rack" )
	w, h = RACK_WIDTH, RACK_HEIGHT
	p.box( "armory_frame", ( 1.0, 0, 0 ), ( 2.0, w, h ) )                       # backboard
	p.box( "armory_plate", ( 2.2, 0, 0 ), ( 0.6, w - 8, h - 14 ) )               # face plate
	p.box( "armory_red", ( 2.6, 0, h / 2 - 9 ), ( 0.4, w - 8, 2.5 ) )            # stripe
	p.box( "armory_frame", ( 4.0, 0, h / 2 - 2 ), ( 8.0, w, 4.0 ) )              # top rail
	p.box( "armory_frame", ( 5.0, 0, -h / 2 + 3 ), ( 10.0, w, 6.0 ) )            # bottom shelf
	for side in ( -1, 1 ):
		p.box( "armory_frame", ( 4.0, side * ( w / 2 - 2 ), 0 ), ( 8.0, 4.0, h ) )  # side posts
	for i in range( CRADLES ):
		y = ( i - ( CRADLES - 1 ) / 2 ) * 24.0
		p.box( "armory_rubber", ( 7.5, y, -h / 2 + 7 ), ( 6.0, 6.0, 3.0 ) )      # butt cradle
		p.box( "armory_rubber", ( 6.5, y, h / 2 - 12 ), ( 5.0, 5.0, 3.0 ) )      # barrel clip
		p.box( "armory_glow", ( 2.8, y, -h / 2 + 12 ), ( 0.4, 3.0, 1.2 ) )       # slot lamp
	p.box( "armory_amber", ( 2.8, w / 2 - 14, h / 2 - 9 ), ( 0.5, 8.0, 2.0 ) )  # label lamp
	return p.build()


def ammo_crate():
	"""A blaster-cell crate on the floor: a gunmetal case with pale lid and corner guards, carry handles and a window
	of glowing charged cells on its front."""
	p = Part( "ammo_crate" )
	L, W, H = 30.0, 44.0, 26.0          # depth (x), width (y), height (z)
	p.box( "armory_frame", ( 0, 0, H / 2 ), ( L, W, H ) )                        # case
	p.box( "armory_plate", ( 0, 0, H + 1.0 ), ( L + 1, W + 1, 2.0 ) )            # lid
	p.box( "armory_red", ( 0, 0, H + 2.2 ), ( L - 6, 4.0, 0.5 ) )                # lid stripe
	for sx in ( -1, 1 ):
		for sy in ( -1, 1 ):
			p.box( "armory_plate", ( sx * ( L / 2 - 1 ), sy * ( W / 2 - 1 ), H / 2 ), ( 3.0, 3.0, H + 1 ) )   # corner guards
	p.box( "armory_rubber", ( 0, W / 2 + 1.0, H - 6 ), ( 12.0, 2.0, 2.5 ) )      # handles
	p.box( "armory_rubber", ( 0, -W / 2 - 1.0, H - 6 ), ( 12.0, 2.0, 2.5 ) )
	p.box( "armory_rubber", ( L / 2 + 0.3, 0, H / 2 - 1 ), ( 0.6, W - 12, 12.0 ) )      # window frame
	for i in range( 6 ):
		y = ( i - 2.5 ) * 5.5
		p.box( "armory_glow", ( L / 2 + 0.6, y, H / 2 - 1 ), ( 0.4, 3.2, 9.0 ) )       # cells
	p.box( "armory_glow", ( L / 2 + 0.6, W / 2 - 5, H - 4 ), ( 0.4, 2.0, 2.0 ) )      # status lamp
	return p.build()


