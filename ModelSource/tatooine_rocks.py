def write_material():
	path = os.path.join( ASSETS, MAT )
	os.makedirs( os.path.dirname( path ), exist_ok=True )
	with open( path, "w", newline="\n" ) as fh:
		fh.write( "\n".join( [
			"// Generated by ModelSource/tatooine_rocks.py", "", "Layer0", "{", '\tshader "shaders/complex.shader"', "",
			'\tTextureColor "materials/tatooine/rock_color.png"', '\tTextureNormal "materials/tatooine/rock_normal.png"',
			'\tTextureRoughness "materials/tatooine/rock_rough.png"', '\tTextureAmbientOcclusion "materials/tatooine/rock_ao.png"',
			'\tg_flMetalness "0.000"', '\tg_bFogEnabled "1"', "}", "" ] ) )


def fbm( p, octaves=4 ):
	return noise.fractal( p, 1.0, 2.0, octaves, noise_basis="PERLIN_ORIGINAL" )


def displace( bm, seed, amp, freq, strata=0.0, strata_step=40.0 ):
	"""Push each vertex along its normal by noise; strata adds horizontal grooves (wind-cut layers)."""
	off = Vector( ( seed * 17.3, seed * 5.1, seed * 9.7 ) )
	bm.normal_update()
	for v in bm.verts:
		p = v.co * freq + off
		d = fbm( p ) * amp + noise.noise( p * 3.1 ) * amp * 0.25
		if strata:
			f = v.co.z / strata_step
			d -= strata * ( 0.5 - 0.5 * math.cos( ( f - math.floor( f ) ) * math.pi * 2 ) ) ** 3
		v.co += v.normal * d


def box_uv( bm, scale ):
	uv = bm.loops.layers.uv.verify()
	for f in bm.faces:
		n = f.normal
		ax = max( range( 3 ), key=lambda i: abs( n[i] ) )
		for l in f.loops:
			c = l.vert.co
			if ax == 2:
				l[uv].uv = ( c.x / scale, c.y / scale )
			elif ax == 0:
				l[uv].uv = ( c.y / scale, c.z / scale )
			else:
				l[uv].uv = ( c.x / scale, c.z / scale )


def sink( bm, depth ):
	"""Flatten the underside and drop it below the sand line."""
	low = min( v.co.z for v in bm.verts )
	for v in bm.verts:
		v.co.z -= low + depth
		if v.co.z < -depth * 0.6:
			v.co.z = -depth * 0.6 - ( -depth * 0.6 - v.co.z ) * 0.2


def boulder( seed, size, squash=( 1.0, 0.85, 0.65 ) ):
	bm = bmesh.new()
	bmesh.ops.create_icosphere( bm, subdivisions=4, radius=1.0 )
	for v in bm.verts:
		v.co = Vector( ( v.co.x * size * squash[0], v.co.y * size * squash[1], v.co.z * size * squash[2] ) )
	displace( bm, seed, size * 0.28, 1.6 / size, strata=size * 0.05, strata_step=size * 0.22 )
	sink( bm, size * 0.18 )
	return bm


def spire( seed, height, radius ):
	"""A hoodoo: a layered column narrowing to a neck under a wider cap."""
	bm = bmesh.new()
	rings, segs = 14, 14
	random.seed( seed )
	for i in range( rings + 1 ):
		t = i / rings
		r = radius * ( 1.0 - 0.55 * t + 0.5 * max( 0.0, t - 0.82 ) / 0.18 * ( t > 0.82 ) )
		r *= 1.0 + 0.12 * math.sin( t * 19 + seed )
		ring = []
		for j in range( segs ):
			a = j / segs * math.pi * 2
			ring.append( bm.verts.new( ( math.cos( a ) * r, math.sin( a ) * r, t * height ) ) )
		if i:
			for j in range( segs ):
				bm.faces.new( ( prev[j], prev[( j + 1 ) % segs], ring[( j + 1 ) % segs], ring[j] ) )
		else:
			bm.faces.new( list( reversed( ring ) ) )
		prev = ring
	bm.faces.new( prev )
	bmesh.ops.subdivide_edges( bm, edges=bm.edges[:], cuts=1, use_grid_fill=True )
	displace( bm, seed, radius * 0.22, 2.2 / radius, strata=radius * 0.12, strata_step=height / 9 )
	sink( bm, radius * 0.4 )
	return bm


def export( name, bm ):
	bmesh.ops.recalc_face_normals( bm, faces=bm.faces[:] )
	box_uv( bm, 220.0 )
	for f in bm.faces:
		f.smooth = True
	me = bpy.data.meshes.new( name )
	bm.to_mesh( me )
	bm.free()
	ob = bpy.data.objects.new( name, me )
	bpy.context.scene.collection.objects.link( ob )
	ob.data.materials.append( bpy.data.materials.get( MAT ) or bpy.data.materials.new( MAT ) )
	bpy.ops.object.select_all( action="DESELECT" )
	ob.select_set( True )
	os.makedirs( OUT, exist_ok=True )
	fbx = f"{name}_{REV}"
	bpy.ops.export_scene.fbx( filepath=os.path.join( OUT, fbx + ".fbx" ), use_selection=True, mesh_smooth_type="FACE", axis_forward="Y", axis_up="Z" )
	with open( os.path.join( OUT, fbx + ".fbx.meta" ), "w", newline="\n" ) as fh:
		fh.write( '{\n  "guid": "%s"\n}' % uuid.uuid4() )
	with open( os.path.join( OUT, name + ".vmdl" ), "w", newline="\n" ) as fh:
		fh.write( VMDL % { "fbx": f"models/tatooine/{fbx}.fbx" } )
	# keep this revision and the one before (the editor caches FBX imports by name)
	revs = sorted( ( f for f in os.listdir( OUT ) if f.startswith( name + "_" ) and f.endswith( ".fbx" ) and len( f ) == len( name ) + 11 ), key=lambda f: os.path.getmtime( os.path.join( OUT, f ) ) )
	for old in revs[:-2]:
		for fn in ( old, old + ".meta" ):
			try:
				os.remove( os.path.join( OUT, fn ) )
			except OSError:
				pass
	print( "ROCK", name, len( me.polygons ), "faces" )
	bpy.data.objects.remove( ob, do_unlink=True )


