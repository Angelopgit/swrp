"""
Blasters from the Galactic Contention Squad mod (Workshop 2428425228) where theirs beat what we had (Angelo, 2026-10-14: the
BF2 DC-15A's texture showed white seams and smears). LOCAL ONLY: the GC team published no reuse terms; never publish or commit.
Exported first with X:\\SWRP Projects\\Squad_Mod_2428425228\\Tools\\GcExport (export <dir> Art/Weapons/DC15A_2021 ...) as glTF plus
CUE4Parse material .json and PNG textures.

    "C:\\Program Files\\Blender Foundation\\Blender 5.2\\blender.exe" -b --factory-startup -P ModelSource/gc_weapons.py

Each gun goes into the game's grip frame (grip at the origin, barrel +X, up +Z, inches) like ModelSource/bf2_props.py: the GC
model already points +X; it's moved so the bottom of its pistol grip sits where the BF2 model's did (SHIFT, measured), so the
hands and the TFA stats' muzzle numbers carry over. Writes Assets/models/weapons/gc_<name>_<rev>.fbx, gc_<name>.vmdl and its
vmats/PNGs in gctex/ (UE ORM masks split into AO / roughness / metalness).
"""
import os
import sys
import json
import uuid

import bpy
import numpy as np
from mathutils import Vector, Matrix

HERE = os.path.dirname( os.path.abspath( __file__ ) )
PROJECT = os.path.dirname( HERE )
sys.path.insert( 0, HERE )
import bf2_props as bp

EXPORT = r"X:\SWRP Projects\Squad_Mod_2428425228\Export"
OUT = os.path.join( PROJECT, "Assets", "models", "weapons" )
TEX = os.path.join( OUT, "gctex" )
M = 39.3701

# name -> (glb under the export folder, shift in inches after scaling, objects to drop)
GUNS = {
	"dc15a": ( r"dc15a\ANE_BASE\Art\Weapons\DC15A_2021\DC15A.glb", ( 8.0, 0.0, 0.7 ), { "Icosphere" } ),
}


def material_json( name ):
	for root, _, files in os.walk( EXPORT ):
		for f in files:
			if f.lower() == name.lower() + ".json":
				return os.path.join( root, f )
	return None


def tex_png( obj_path ):
	p = obj_path.rsplit( ".", 1 )[0].lstrip( "/" )
	for sub in os.listdir( EXPORT ):
		full = os.path.join( EXPORT, sub, *p.split( "/" ) ) + ".png"
		if os.path.exists( full ):
			return full
	return None


def pick( textures, keys ):
	for k in keys:
		if k in textures:
			return tex_png( textures[k]["ObjectPath"] )
	return None


def read( path ):
	img = bpy.data.images.load( path, check_existing=False )
	w, h = img.size
	a = np.array( img.pixels[:], dtype=np.float32 ).reshape( h, w, 4 )
	bpy.data.images.remove( img )
	return a, w, h


def convert( mat_name, out_name ):
	"""One GC material -> PNGs + vmat; returns the vmat's asset path."""
	os.makedirs( TEX, exist_ok=True )
	rel = f"models/weapons/gctex/{out_name}.vmat"
	j = material_json( mat_name )
	textures = json.load( open( j ) ).get( "Textures", {} ) if j else {}
	color = pick( textures, ( "Base Color", "PM_Diffuse", "BaseColor", "Diffuse" ) )
	normal = pick( textures, ( "Normal", "PM_Normals" ) )
	orm = pick( textures, ( "ORMS", "ORM", "PM_SpecularMasks", "AORM" ) )
	lines = []
	if color:
		a, w, h = read( color )
		bp.write( os.path.join( TEX, f"{out_name}_color.png" ), a[:, :, :3], w, h )
		lines.append( f'\tTextureColor "models/weapons/gctex/{out_name}_color.png"' )
	else:
		lines.append( '\tTextureColor "materials/default/default_color.tga"' )
	if normal:
		a, w, h = read( normal )
		bp.write( os.path.join( TEX, f"{out_name}_normal.png" ), a[:, :, :3], w, h )
		lines.append( f'\tTextureNormal "models/weapons/gctex/{out_name}_normal.png"' )
	else:
		lines.append( '\tTextureNormal "materials/default/default_normal.tga"' )
	metal = False
	if orm:
		a, w, h = read( orm )
		bp.write( os.path.join( TEX, f"{out_name}_ao.png" ), a[:, :, 0], w, h )
		bp.write( os.path.join( TEX, f"{out_name}_rough.png" ), a[:, :, 1], w, h )
		bp.write( os.path.join( TEX, f"{out_name}_metal.png" ), a[:, :, 2] * 0.25, w, h )      # (0.6 left the dark gunmetal near-black under the ship lamps, Angelo 2026-10-14)
		lines += [f'\tTextureAmbientOcclusion "models/weapons/gctex/{out_name}_ao.png"',
			f'\tTextureRoughness "models/weapons/gctex/{out_name}_rough.png"',
			f'\tTextureMetalness "models/weapons/gctex/{out_name}_metal.png"']
		metal = True
	else:
		lines += ['\tTextureRoughness "materials/default/default_rough.tga"', '\tg_flMetalness "0.300"']
	vm = ["// Generated by ModelSource/gc_weapons.py from Galactic Contention textures (local only, never publish)", "", "Layer0", "{",
		'\tshader "shaders/complex.shader"', ""]
	if metal:
		vm.append( "\tF_METALNESS_TEXTURE 1" )
	vm += ['\tg_flModelTintAmount "1.000"', '\tg_vColorTint "[1.000000 1.000000 1.000000 0.000000]"'] + lines + ["}"]
	with open( os.path.join( TEX, out_name + ".vmat" ), "w", newline="\n" ) as fh:
		fh.write( "\n".join( vm ) + "\n" )
	print( f"GCWPN material {mat_name}: color {bool( color )}, normal {bool( normal )}, orm {bool( orm )}" )
	return rel


def build( name, glb, shift, drop ):
	bpy.ops.wm.read_factory_settings( use_empty=True )
	bpy.ops.import_scene.gltf( filepath=os.path.join( EXPORT, glb ) )
	meshes = [o for o in bpy.data.objects if o.type == "MESH" and o.name not in drop]
	mtx = Matrix.Translation( Vector( shift ) ) @ Matrix.Scale( M, 4 )
	slots = {}
	for o in meshes:
		me = o.data
		me.transform( mtx @ o.matrix_world )
		for i, m in enumerate( me.materials ):
			if m and m.name not in slots:
				slots[m.name] = convert( m.name, f"gc_{name}_{m.name.lower().replace( '-', '_' )}" )
		for i, m in enumerate( me.materials ):
			if m:
				me.materials[i] = bpy.data.materials.get( slots[m.name] ) or bpy.data.materials.new( slots[m.name] )
	for o in list( bpy.data.objects ):
		if o not in meshes:
			bpy.data.objects.remove( o, do_unlink=True )
	for o in meshes:
		o.parent = None
		o.matrix_world = Matrix.Identity( 4 )
	bpy.ops.object.select_all( action="DESELECT" )
	for o in meshes:
		o.select_set( True )
	bpy.context.view_layer.objects.active = meshes[0]
	if len( meshes ) > 1:
		bpy.ops.object.join()
	ob = bpy.context.view_layer.objects.active
	lo, hi = bp.bounds( [ob] )
	fbx = f"gc_{name}_{bp.REV}"
	bpy.ops.export_scene.fbx( filepath=os.path.join( OUT, fbx + ".fbx" ), use_selection=True, mesh_smooth_type="FACE", axis_forward="Y", axis_up="Z" )
	with open( os.path.join( OUT, fbx + ".fbx.meta" ), "w", newline="\n" ) as fh:
		fh.write( '{\n  "guid": "%s"\n}' % uuid.uuid4() )
	tip = [v.co for v in ob.data.vertices if v.co.x > hi.x - 1.0]
	mz = sum( p.z for p in tip ) / len( tip ) if tip else 0.0
	with open( os.path.join( OUT, f"gc_{name}.vmdl" ), "w", newline="\n" ) as fh:
		fh.write( bp.VMDL % { "fbx": f"models/weapons/{fbx}.fbx", "extra": bp.ATTACH % { "x": hi.x, "z": mz } } )
	revs = sorted( ( f for f in os.listdir( OUT ) if f.startswith( f"gc_{name}_" ) and f.endswith( ".fbx" ) ),
		key=lambda f: os.path.getmtime( os.path.join( OUT, f ) ) )
	for old in revs[:-2]:
		for fn in ( old, old + ".meta" ):
			try:
				os.remove( os.path.join( OUT, fn ) )
			except OSError:
				pass
	print( f"GCWPN gc_{name}: {len( ob.data.polygons )} faces, muzzle forward {hi.x:.1f} up {mz:.1f}, bounds {[round( x, 1 ) for x in lo]} {[round( x, 1 ) for x in hi]}" )


def main():
	only = sys.argv[sys.argv.index( "--" ) + 1:] if "--" in sys.argv else []
	for name, ( glb, shift, drop ) in GUNS.items():
		if only and name not in only:
			continue
		build( name, glb, shift, drop )


if __name__ == "__main__":
	main()
