def write_materials():
	os.makedirs( MAT_DIR, exist_ok=True )
	for name, ( col, metal, rough, glow ) in MATERIALS.items():
		lines = ["// Generated by ModelSource/hd_props.py", "", "Layer0", "{", '\tshader "shaders/complex.shader"']
		if glow:
			lines.append( "\tF_SELF_ILLUM 1" )
		lines += ["", '\tg_flModelTintAmount "1.000"', '\tg_vColorTint "[%.4f %.4f %.4f 0.000000]"' % col,
			'\tTextureColor "materials/default/default_color.tga"', '\tTextureNormal "materials/default/default_normal.tga"',
			'\tTextureRoughness "materials/default/default_rough.tga"', '\tTextureAmbientOcclusion "materials/default/default_ao.tga"',
			f'\tg_flMetalness "{metal:.3f}"', f'\tg_flRoughnessScaleFactor "{rough:.3f}"', '\tg_bFogEnabled "1"']
		if glow:
			lines += ['\tg_flSelfIllumAlbedoFactor "0.000"', '\tg_flSelfIllumBrightness "3.000"', '\tg_flSelfIllumScale "1.000"',
				'\tg_vSelfIllumTint "[%.4f %.4f %.4f 0.000000]"' % glow, '\tTextureSelfIllumMask "[1.000000 1.000000 1.000000 0.000000]"']
		lines.append( "}" )
		with open( os.path.join( MAT_DIR, name + ".vmat" ), "w", newline="\n" ) as fh:
			fh.write( "\n".join( lines ) + "\n" )


class Builder:
	def __init__( self, name ):
		self.name = name
		self.bm = bmesh.new()
		self.mats = []

	def _mat( self, m ):
		path = f"materials/props/{m}.vmat"
		if path not in self.mats:
			self.mats.append( path )
		return self.mats.index( path )

	def box( self, m, center, size, bevel=0.15, rot=None ):
		g = bmesh.ops.create_cube( self.bm, size=1.0 )["verts"]
		bmesh.ops.scale( self.bm, vec=Vector( size ), verts=g )
		if rot:
			bmesh.ops.rotate( self.bm, verts=g, cent=Vector(), matrix=Matrix.Rotation( math.radians( rot[1] ), 3, rot[0] ) )
		bmesh.ops.translate( self.bm, vec=Vector( center ), verts=g )
		self._finish( g, m, bevel )

	def cyl( self, m, center, length, radius, axis="X", segs=16, bevel=0.1 ):
		g = bmesh.ops.create_cone( self.bm, cap_ends=True, segments=segs, radius1=radius, radius2=radius, depth=length )["verts"]
		if axis == "X":
			bmesh.ops.rotate( self.bm, verts=g, cent=Vector(), matrix=Matrix.Rotation( math.radians( 90 ), 3, "Y" ) )
		elif axis == "Y":
			bmesh.ops.rotate( self.bm, verts=g, cent=Vector(), matrix=Matrix.Rotation( math.radians( 90 ), 3, "X" ) )
		bmesh.ops.translate( self.bm, vec=Vector( center ), verts=g )
		self._finish( g, m, bevel )

	def _finish( self, verts, m, bevel ):
		idx = self._mat( m )
		faces = { f for v in verts for f in v.link_faces }
		for f in faces:
			f.material_index = idx
			f.smooth = False
		if bevel > 0:
			edges = list( { e for f in faces for e in f.edges } )
			bmesh.ops.bevel( self.bm, geom=edges, offset=bevel, segments=2, affect="EDGES", profile=0.5 )

	def export( self ):
		me = bpy.data.meshes.new( self.name )
		self.bm.to_mesh( me )
		ob = bpy.data.objects.new( self.name, me )
		bpy.context.scene.collection.objects.link( ob )
		for p in self.mats:
			ob.data.materials.append( bpy.data.materials.get( p ) or bpy.data.materials.new( p ) )
		bpy.ops.object.select_all( action="DESELECT" )
		ob.select_set( True )
		os.makedirs( OUT, exist_ok=True )
		fbx = f"{self.name}_{bp.REV}"
		bpy.ops.export_scene.fbx( filepath=os.path.join( OUT, fbx + ".fbx" ), use_selection=True, mesh_smooth_type="FACE", axis_forward="Y", axis_up="Z" )
		meta = os.path.join( OUT, fbx + ".fbx.meta" )
		if not os.path.exists( meta ):
			with open( meta, "w", newline="\n" ) as fh:
				fh.write( '{\n  "guid": "%s"\n}' % uuid.uuid4() )
		with open( os.path.join( OUT, self.name + ".vmdl" ), "w", newline="\n" ) as fh:
			fh.write( bp.VMDL % { "fbx": f"models/props/{fbx}.fbx", "extra": bp.PHYS } )
		revs = sorted( ( f for f in os.listdir( OUT ) if f.startswith( self.name + "_" ) and f.endswith( ".fbx" ) and len( f ) == len( self.name ) + 11 ), key=lambda f: os.path.getmtime( os.path.join( OUT, f ) ) )
		for old in revs[:-2]:
			for fn in ( old, old + ".meta" ):
				try:
					os.remove( os.path.join( OUT, fn ) )
				except OSError:
					pass
		bpy.data.objects.remove( ob, do_unlink=True )
		print( "HDPROP", self.name )


