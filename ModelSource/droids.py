def vmdl_for( name, fbx, mats ):
	"""The clone drill vmdl with this droid's mesh and materials (no jetpack body group)."""
	s = open( TEMPLATE_VMDL, encoding="utf-8" ).read()
	s = s.replace( "models/clones/clone_trooper_r4.fbx", f"models/droids/{fbx}.fbx" )
	remaps = "".join( f'\t\t\t\t\t\t\t{{\n\t\t\t\t\t\t\t\tfrom = "{m}.vmat"\n\t\t\t\t\t\t\t\tto = "models/droids/materials/{m}.vmat"\n\t\t\t\t\t\t\t}},\n' for m in mats )
	s = re.sub( r"(remaps = \n\t\t\t\t\t\t\[\n).*?(\t\t\t\t\t\t\])", lambda m: m.group( 1 ) + remaps + m.group( 2 ), s, count=1, flags=re.S )
	# one render mesh, no jetpack
	s = re.sub( r'\t\t\t\t\t\{\n\t\t\t\t\t\t_class = "RenderMeshFile"\n\t\t\t\t\t\tname = "jetpack".*?\n\t\t\t\t\t\},\n', "", s, count=1, flags=re.S )
	s = re.sub( r'exception_list = \n\t\t\t\t\t\t\t\[\n\t\t\t\t\t\t\t\t"jetpack",\n\t\t\t\t\t\t\t\]', "exception_list = [  ]", s, count=1 )
	s = re.sub( r'\t\t\t\{\n\t\t\t\t_class = "BodyGroupList".*?\n\t\t\t\},\n', "", s, count=1, flags=re.S )
	s = s.replace( 'name = "clone_trooper"', f'name = "{name}"' )
	assert "jetpack" not in s, "template changed: jetpack still referenced"
	return s


def export( obj, arm ):
	os.makedirs( MODEL_DIR, exist_ok=True )
	name = obj.name
	fbx = f"{name}_{REV}"
	bpy.ops.object.select_all( action="DESELECT" )
	arm.select_set( True )
	obj.select_set( True )
	bpy.context.view_layer.objects.active = arm
	# the clone models' own export settings (fix_weights.py), so the skeleton and its bind pose match exactly
	bpy.ops.export_scene.fbx( filepath=os.path.join( MODEL_DIR, fbx + ".fbx" ), use_selection=True, object_types={ "ARMATURE", "MESH" },
		add_leaf_bones=False, primary_bone_axis="X", secondary_bone_axis="Z", bake_anim=True, bake_anim_use_all_actions=False,
		bake_anim_use_nla_strips=False, bake_anim_force_startend_keying=True, mesh_smooth_type="FACE" )
	meta = os.path.join( MODEL_DIR, fbx + ".fbx.meta" )
	if not os.path.exists( meta ):
		with open( meta, "w", newline="\n" ) as fh:
			fh.write( '{\n  "guid": "%s"\n}' % uuid.uuid4() )
	with open( os.path.join( MODEL_DIR, name + ".vmdl" ), "w", newline="\n" ) as fh:
		fh.write( vmdl_for( name, fbx, [m.name for m in obj.data.materials] ) )

	revs = sorted( ( f for f in os.listdir( MODEL_DIR ) if f.startswith( name + "_" ) and f.endswith( ".fbx" ) ),
		key=lambda f: os.path.getmtime( os.path.join( MODEL_DIR, f ) ) )
	for old in revs[:-2]:
		for fn in ( old, old + ".meta" ):
			try:
				os.remove( os.path.join( MODEL_DIR, fn ) )
			except OSError:
				pass


def main():
	bpy.ops.wm.open_mainfile( filepath=SKELETON_BLEND )
	arm = bpy.data.objects["Human Citizen Armature"]
	# only the skeleton is used: drop the clone meshes and helpers
	for o in list( bpy.data.objects ):
		if o != arm:
			bpy.data.objects.remove( o, do_unlink=True )
	arm.data.pose_position = "REST"
	write_materials()
	for build in ( b1, b2, commander ):
		obj = build( arm )
		export( obj, arm )
		print( f"DROID {obj.name}: {len( obj.data.polygons )} faces, {len( obj.vertex_groups )} bones used" )
		bpy.data.objects.remove( obj, do_unlink=True )


main()
