def write_materials():
	os.makedirs( os.path.join( MODEL_DIR, "materials" ), exist_ok=True )
	for name, ( tint, metal, rough, glow ) in MATERIALS.items():
		lines = ["// Generated by ModelSource/droids.py", "", "Layer0", "{", '\tshader "shaders/complex.shader"', ""]
		if glow:
			lines.append( "\tF_SELF_ILLUM 1" )
		lines += [
			'\tg_flModelTintAmount "0.000"',
			'\tg_vColorTint "[%.4f %.4f %.4f 0.000000]"' % tint,
			'\tTextureColor "[%.4f %.4f %.4f 0.000000]"' % tint,
			'\tTextureNormal "materials/default/default_normal.tga"',
			'\tTextureRoughness "materials/default/default_rough.tga"',
			'\tTextureAmbientOcclusion "materials/default/default_ao.tga"',
			f'\tg_flMetalness "{metal:.3f}"',
			f'\tg_flRoughnessScaleFactor "{rough:.3f}"',
		]
		if glow:
			lines += [
				'\tg_flSelfIllumAlbedoFactor "0.000"', '\tg_flSelfIllumBrightness "3.000"', '\tg_flSelfIllumScale "1.000"',
				'\tg_vSelfIllumTint "[%.4f %.4f %.4f 0.000000]"' % glow,
				'\tTextureSelfIllumMask "[1.000000 1.000000 1.000000 0.000000]"',
			]
		lines.append( "}" )
		with open( os.path.join( MODEL_DIR, "materials", name + ".vmat" ), "w", newline="\n" ) as fh:
			fh.write( "\n".join( lines ) + "\n" )


# ---------------------------------------------------------------------------------------------------------------------
# Rigid-skinned parts: every primitive is weighted fully to one bone
# ---------------------------------------------------------------------------------------------------------------------

class Droid:
	def __init__( self, name, arm ):
		self.name = name
		self.arm = arm
		self.mw = arm.matrix_world
		self.bm = bmesh.new()
		self.mats = []
		self.groups = []          # bone name per vertex
		self.deform = self.bm.verts.layers.deform.verify()

	def head( self, bone ):
		return self.mw @ self.arm.data.bones[bone].head_local

	def slot( self, mat ):
		if mat not in self.mats:
			self.mats.append( mat )
		return self.mats.index( mat )

	def _add( self, geom, mat, bone ):
		verts = [g for g in geom if isinstance( g, bmesh.types.BMVert )]
		faces = {f for v in verts for f in v.link_faces}
		for f in faces:
			f.material_index = self.slot( mat )
		if bone not in self.groups:
			self.groups.append( bone )
		gi = self.groups.index( bone )
		for v in verts:
			v[self.deform][gi] = 1.0

	def box( self, mat, bone, center, size, rot=None ):
		m = Matrix.Translation( Vector( center ) ) @ ( rot.to_matrix().to_4x4() if rot is not None else Matrix.Identity( 4 ) ) @ Matrix.Diagonal( ( size[0], size[1], size[2], 1 ) )
		geom = bmesh.ops.create_cube( self.bm, size=1.0, matrix=m )["verts"]
		self._add( geom, mat, bone )

	def rod( self, mat, bone, a, b, r, r2=None, segments=8 ):
		"""A cylinder from point a to point b (a cone if r2 differs)."""
		a, b = Vector( a ), Vector( b )
		d = b - a
		rot = d.to_track_quat( "Z", "Y" )
		m = Matrix.Translation( ( a + b ) / 2 ) @ rot.to_matrix().to_4x4()
		geom = bmesh.ops.create_cone( self.bm, cap_ends=True, segments=segments, radius1=r, radius2=r if r2 is None else r2, depth=d.length, matrix=m )["verts"]
		self._add( geom, mat, bone )

	def ball( self, mat, bone, center, r, scale=( 1, 1, 1 ) ):
		m = Matrix.Translation( Vector( center ) ) @ Matrix.Diagonal( ( scale[0], scale[1], scale[2], 1 ) )
		geom = bmesh.ops.create_uvsphere( self.bm, u_segments=10, v_segments=6, radius=r, matrix=m )["verts"]
		self._add( geom, mat, bone )

	def build( self ):
		me = bpy.data.meshes.new( self.name )
		self.bm.to_mesh( me )
		self.bm.free()
		obj = bpy.data.objects.new( self.name, me )
		bpy.context.scene.collection.objects.link( obj )
		for m in self.mats:
			mat = bpy.data.materials.get( m ) or bpy.data.materials.new( m )
			me.materials.append( mat )
		for g in self.groups:
			obj.vertex_groups.new( name=g )
		obj.parent = self.arm
		mod = obj.modifiers.new( "Armature", "ARMATURE" )
		mod.object = self.arm
		for p in me.polygons:
			p.use_smooth = False
		return obj


FWD = Vector( ( 0, -1, 0 ) )       # the skeleton faces -Y
UP = Vector( ( 0, 0, 1 ) )


def limbs( d, mat, joint, r_up, r_low, r_thigh, r_shin, hand=0.035, foot=( 0.08, 0.2, 0.045 ) ):
	"""Arms and legs as rods between the joints, a ball at every elbow and knee, block hands and feet."""
	for s in "LR":
		sh, el, wr = d.head( f"arm_upper_{s}" ), d.head( f"arm_lower_{s}" ), d.head( f"hand_{s}" )
		d.ball( joint, f"arm_upper_{s}", sh, r_up * 1.4 )
		d.rod( mat, f"arm_upper_{s}", sh, el, r_up )
		d.ball( joint, f"arm_lower_{s}", el, r_up * 1.15 )
		d.rod( mat, f"arm_lower_{s}", el, wr, r_low )
		d.box( joint, f"hand_{s}", wr + ( wr - el ).normalized() * 0.04, ( hand * 2, hand * 2, hand * 2.4 ) )

		hip, knee, ank = d.head( f"leg_upper_{s}" ), d.head( f"leg_lower_{s}" ), d.head( f"ankle_{s}" )
		d.ball( joint, f"leg_upper_{s}", hip, r_thigh * 1.3 )
		d.rod( mat, f"leg_upper_{s}", hip, knee, r_thigh )
		d.ball( joint, f"leg_lower_{s}", knee, r_thigh * 1.15 )
		d.rod( mat, f"leg_lower_{s}", knee, ank, r_shin )
		d.box( mat, f"ankle_{s}", Vector( ( ank.x, ank.y - foot[1] * 0.3, foot[2] * 0.5 ) ), foot )


def b1( arm ):
	d = Droid( "droid_b1", arm )
	tan, dark, eye = "droid_b1", "droid_b1_dark", "droid_eye"
	pelvis, chest, neck, head = d.head( "pelvis" ), d.head( "spine_2" ), d.head( "neck_0" ), d.head( "head" )

	d.box( tan, "pelvis", pelvis + Vector( ( 0, 0, -0.02 ) ), ( 0.2, 0.1, 0.09 ) )
	d.rod( dark, "spine_0", pelvis, chest, 0.022 )                                   # the thin spine
	d.box( tan, "spine_2", chest + Vector( ( 0, 0.0, 0.08 ) ), ( 0.3, 0.13, 0.2 ) )   # chest plate
	d.box( dark, "spine_2", chest + Vector( ( 0, 0.11, 0.06 ) ), ( 0.17, 0.09, 0.17 ) )   # backpack
	d.box( tan, "spine_2", chest + Vector( ( 0, -0.075, 0.12 ) ), ( 0.08, 0.03, 0.06 ) )   # chest marking
	d.rod( dark, "neck_0", neck + Vector( ( 0, 0, -0.04 ) ), head, 0.018 )            # long neck
	# the long sloping head: a flat snout reaching forward and down, eyes at the back
	tilt = Matrix.Rotation( 0.35, 4, "X" ).to_quaternion()
	d.box( tan, "head", head + FWD * 0.1 + Vector( ( 0, 0, 0.0 ) ), ( 0.075, 0.28, 0.085 ), tilt )
	d.ball( eye, "head", head + FWD * 0.015 + Vector( ( 0.035, 0, 0.015 ) ), 0.018 )
	d.ball( eye, "head", head + FWD * 0.015 + Vector( ( -0.035, 0, 0.015 ) ), 0.018 )
	limbs( d, tan, dark, 0.024, 0.021, 0.03, 0.026 )
	return d.build()


def b2( arm ):
	d = Droid( "droid_b2", arm )
	plate, dark = "droid_b2", "droid_b2_dark"
	pelvis, chest, neck, head = d.head( "pelvis" ), d.head( "spine_2" ), d.head( "neck_0" ), d.head( "head" )

	d.box( plate, "pelvis", pelvis + Vector( ( 0, 0, -0.03 ) ), ( 0.28, 0.16, 0.12 ) )
	d.rod( dark, "spine_0", pelvis, chest, 0.06 )
	# the massive upper body, hunched forward, the head sunk into it
	d.box( plate, "spine_2", chest + Vector( ( 0, 0.02, 0.1 ) ), ( 0.52, 0.32, 0.36 ), Matrix.Rotation( 0.12, 4, "X" ).to_quaternion() )
	d.box( dark, "spine_2", chest + Vector( ( 0, -0.15, 0.06 ) ), ( 0.3, 0.04, 0.16 ) )
	d.box( plate, "head", head + Vector( ( 0, -0.03, -0.05 ) ), ( 0.13, 0.13, 0.07 ) )
	d.ball( "droid_eye", "head", head + Vector( ( 0, -0.1, -0.05 ) ), 0.02, ( 2.2, 0.6, 0.6 ) )
	for s, x in ( ( "L", 1 ), ( "R", -1 ) ):
		# shoulder armour and the wrist-blaster forearms
		d.box( plate, f"arm_upper_{s}", d.head( f"arm_upper_{s}" ) + Vector( ( 0.03 * x, 0, 0.03 ) ), ( 0.16, 0.18, 0.12 ) )
		el, wr = d.head( f"arm_lower_{s}" ), d.head( f"hand_{s}" )
		d.rod( plate, f"arm_lower_{s}", el, wr, 0.06, 0.055, segments=6 )
		d.rod( dark, f"arm_lower_{s}", wr, wr + ( wr - el ).normalized() * 0.07, 0.025 )   # blaster muzzle
	limbs( d, plate, dark, 0.045, 0.05, 0.055, 0.05, hand=0.04, foot=( 0.11, 0.24, 0.06 ) )
	return d.build()


def commander( arm ):
	"""A tall tactical droid: narrow body, long limbs, a round flat head with a crest."""
	d = Droid( "droid_commander", arm )
	steel, dark = "droid_cmd", "droid_cmd_dark"
	pelvis, chest, neck, head = d.head( "pelvis" ), d.head( "spine_2" ), d.head( "neck_0" ), d.head( "head" )

	d.box( steel, "pelvis", pelvis + Vector( ( 0, 0, -0.02 ) ), ( 0.2, 0.12, 0.1 ) )
	d.rod( dark, "spine_0", pelvis, chest, 0.035 )
	d.box( steel, "spine_2", chest + Vector( ( 0, 0, 0.08 ) ), ( 0.34, 0.16, 0.24 ) )
	d.box( dark, "spine_2", chest + Vector( ( 0, -0.085, 0.04 ) ), ( 0.12, 0.02, 0.2 ) )
	for s, x in ( ( "L", 1 ), ( "R", -1 ) ):
		d.box( steel, "spine_2", chest + Vector( ( 0.19 * x, 0, 0.17 ) ), ( 0.1, 0.16, 0.05 ) )     # shoulder fins
	d.rod( dark, "neck_0", neck, head, 0.025 )
	d.rod( steel, "head", head + Vector( ( 0, 0, 0.0 ) ), head + Vector( ( 0, 0, 0.06 ) ), 0.13, 0.12, segments=14 )   # the flat disc head
	d.box( steel, "head", head + Vector( ( 0, 0, 0.09 ) ), ( 0.03, 0.22, 0.05 ) )                # crest
	d.ball( "droid_eye", "head", head + FWD * 0.11 + Vector( ( 0.04, 0, 0.03 ) ), 0.018 )
	d.ball( "droid_eye", "head", head + FWD * 0.11 + Vector( ( -0.04, 0, 0.03 ) ), 0.018 )
	limbs( d, steel, dark, 0.03, 0.026, 0.035, 0.03 )
	return d.build()


