"""
An original bacta pod for SWRP's medbay, built from primitives (no ripped or downloaded models): a plinth with a control
panel, a rear spine with feed pipes, a cap with lamps, a glass tank that sinks into the floor to let you in, and the
bacta that fills it. Three models so the glass and the liquid can move on their own.

    "C:\\Program Files\\Blender Foundation\\Blender 5.2\\blender.exe" -b --factory-startup -P ModelSource/bacta_pod.py

Units are s&box units. Origin on the floor at the tank's centre, the front (the control panel) facing +X. The tank's
inside is 26 units in radius and the glass runs from 12 to 112 above the floor. Writes
Assets/models/medbay/bacta_pod_{frame,glass,liquid}_<rev>.fbx (+ .meta, keeps the previous revision), the vmdls and the
materials in Assets/materials/medbay/.
"""
import os
import math
import time
import uuid

import bpy
import bmesh
from mathutils import Vector, Matrix

HERE = os.path.dirname( os.path.abspath( __file__ ) )
PROJECT = os.path.dirname( HERE )
MODEL_DIR = os.path.join( PROJECT, "Assets", "models", "medbay" )
MAT_DIR = os.path.join( PROJECT, "Assets", "materials", "medbay" )
REV = format( int( time.time() ), "x" )[-6:]

GLASS_R, GLASS_BOTTOM, GLASS_TOP = 28.0, 12.0, 112.0

# name -> (albedo tint, metalness, roughness, emissive tint or None, opacity or None)
MATERIALS = {
	"pod_shell": ( ( 0.85, 0.86, 0.86 ), 0.2, 0.45, None, None ),       # white medical casing
	"pod_dark": ( ( 0.14, 0.15, 0.17 ), 0.6, 0.4, None, None ),         # plinth, spine, pipes
	"pod_steel": ( ( 0.55, 0.57, 0.6 ), 0.85, 0.3, None, None ),        # rings and clamps
	"pod_lamp": ( ( 0.4, 1.0, 0.65 ), 0.0, 0.3, ( 0.35, 1.0, 0.6 ), None ),     # green lamps, panel
	"pod_red": ( ( 0.9, 0.15, 0.1 ), 0.0, 0.3, ( 1.0, 0.2, 0.12 ), None ),      # medical cross
	"pod_glass": ( ( 0.75, 0.9, 0.95 ), 0.0, 0.05, None, 0.22 ),        # the tank
	"pod_bacta": ( ( 0.25, 0.95, 0.55 ), 0.0, 0.1, ( 0.12, 0.45, 0.25 ), 0.55 ),   # the bacta, faintly glowing
}


def mat_path( name ):
	return f"materials/medbay/{name}.vmat"


def write_materials():
	os.makedirs( MAT_DIR, exist_ok=True )
	for name, ( tint, metal, rough, glow, opacity ) in MATERIALS.items():
		lines = ["// Generated by ModelSource/bacta_pod.py", "", "Layer0", "{", '\tshader "shaders/complex.shader"', ""]
		if opacity is not None:
			lines.append( "\tF_TRANSLUCENT 1" )
		if glow:
			lines.append( "\tF_SELF_ILLUM 1" )
		lines += [
			'\tg_flModelTintAmount "1.000"',
			'\tg_vColorTint "[%.4f %.4f %.4f 0.000000]"' % tint,
			'\tTextureColor "materials/default/default_color.tga"',
			'\tTextureNormal "materials/default/default_normal.tga"',
			'\tTextureRoughness "materials/default/default_rough.tga"',
			'\tTextureAmbientOcclusion "materials/default/default_ao.tga"',
			f'\tg_flMetalness "{metal:.3f}"',
			f'\tg_flRoughnessScaleFactor "{rough:.3f}"',
		]
		if opacity is not None:
			lines += [f'\tg_flOpacityScale "{opacity:.3f}"', '\tTextureTranslucency "[1.000000 1.000000 1.000000 0.000000]"']
		if glow:
			lines += [
				'\tg_flSelfIllumAlbedoFactor "0.000"', '\tg_flSelfIllumBrightness "3.000"', '\tg_flSelfIllumScale "1.000"',
				'\tg_vSelfIllumTint "[%.4f %.4f %.4f 0.000000]"' % glow,
				'\tTextureSelfIllumMask "[1.000000 1.000000 1.000000 0.000000]"',
			]
		lines.append( "}" )
		with open( os.path.join( MAT_DIR, name + ".vmat" ), "w", newline="\n" ) as fh:
			fh.write( "\n".join( lines ) + "\n" )


class Part:
	def __init__( self, name ):
		self.name = name
		self.bm = bmesh.new()
		self.slots = []

	def slot( self, mat ):
		if mat not in self.slots:
			self.slots.append( mat )
		return self.slots.index( mat )

	def _tag( self, verts, mat ):
		idx = self.slot( mat )
		for f in { f for v in verts for f in v.link_faces }:
			f.material_index = idx

	def _place( self, verts, center, rot ):
		rx, ry, rz = ( math.radians( a ) for a in rot )
		m = Matrix.Translation( Vector( center ) ) @ Matrix.Rotation( rz, 4, "Z" ) @ Matrix.Rotation( ry, 4, "Y" ) @ Matrix.Rotation( rx, 4, "X" )
		bmesh.ops.transform( self.bm, matrix=m, verts=verts )

	def box( self, mat, center, size, rot=( 0, 0, 0 ) ):
		verts = bmesh.ops.create_cube( self.bm, size=1.0 )["verts"]
		for v in verts:
			v.co = Vector( ( v.co.x * size[0], v.co.y * size[1], v.co.z * size[2] ) )
		self._place( verts, center, rot )
		self._tag( verts, mat )

	def cyl( self, mat, z0, z1, r, segments=24, r2=None, center=( 0, 0 ), rot=( 0, 0, 0 ), open_ends=False ):
		"""An upright cylinder from z0 to z1 (optionally tapering to r2)."""
		h = z1 - z0
		verts = bmesh.ops.create_cone( self.bm, cap_ends=not open_ends, cap_tris=False, segments=segments,
			radius1=r, radius2=r if r2 is None else r2, depth=h )["verts"]
		self._place( verts, ( center[0], center[1], z0 + h / 2 ), rot )
		self._tag( verts, mat )

	def build( self, double_sided=False ):
		if double_sided:
			# glass you can see from inside the tank too: a copy of every face, flipped
			faces = list( self.bm.faces )
			ret = bmesh.ops.duplicate( self.bm, geom=faces )
			new_faces = [g for g in ret["geom"] if isinstance( g, bmesh.types.BMFace )]
			bmesh.ops.reverse_faces( self.bm, faces=new_faces )
		mesh = bpy.data.meshes.new( self.name )
		self.bm.normal_update()
		self.bm.to_mesh( mesh )
		self.bm.free()
		obj = bpy.data.objects.new( self.name, mesh )
		bpy.context.scene.collection.objects.link( obj )
		for m in self.slots:
			obj.data.materials.append( bpy.data.materials.get( mat_path( m ) ) or bpy.data.materials.new( mat_path( m ) ) )
		return obj


def frame():
	"""Everything that stays put: plinth, rear spine with feed pipes, the cap, lamps and the front control panel."""
	p = Part( "bacta_pod_frame" )
	p.cyl( "pod_dark", 0, 8, 38, 8 )                                  # octagonal plinth
	p.cyl( "pod_shell", 8, GLASS_BOTTOM, 34, 24 )                     # base ring
	p.cyl( "pod_steel", GLASS_BOTTOM - 1, GLASS_BOTTOM + 1, GLASS_R + 2, 24, open_ends=True )   # glass seat
	p.box( "pod_lamp", ( 37.5, 0, 6 ), ( 1.0, 18, 3 ) )               # front step light
	# rear spine and pipes
	p.box( "pod_shell", ( -36, 0, 64 ), ( 12, 26, 128 ) )
	p.box( "pod_dark", ( -30.5, 0, 64 ), ( 1.5, 18, 118 ) )
	for y in ( -9, 9 ):
		p.cyl( "pod_steel", 14, 116, 2.2, 10, center=( -29, y ) )
	p.box( "pod_red", ( -42.2, 0, 96 ), ( 0.4, 10, 3 ) )              # medical cross on the back
	p.box( "pod_red", ( -42.2, 0, 96 ), ( 0.4, 3, 10 ) )
	# cap
	p.cyl( "pod_shell", GLASS_TOP, GLASS_TOP + 10, 33, 24 )
	p.cyl( "pod_dark", GLASS_TOP + 10, GLASS_TOP + 16, 26, 24, r2=18 )
	p.cyl( "pod_steel", GLASS_TOP - 1, GLASS_TOP + 1, GLASS_R + 2, 24, open_ends=True )
	p.cyl( "pod_lamp", GLASS_TOP - 0.5, GLASS_TOP + 0.5, 20, 24 )     # light ring shining down into the tank
	for a in range( 0, 360, 60 ):
		x, y = math.cos( math.radians( a ) ) * 31, math.sin( math.radians( a ) ) * 31
		p.box( "pod_lamp", ( x, y, GLASS_TOP + 5 ), ( 2.5, 2.5, 2.0 ), rot=( 0, 0, a ) )
	# front control panel on a little post
	p.box( "pod_dark", ( 44, 0, 18 ), ( 6, 10, 36 ) )
	p.box( "pod_shell", ( 45, 0, 40 ), ( 10, 18, 10 ), rot=( 0, -30, 0 ) )
	p.box( "pod_lamp", ( 47.6, 0, 42.5 ), ( 0.5, 13, 5 ), rot=( 0, -30, 0 ) )
	return p.build()


def glass():
	"""The tank: an open glass tube, double-sided so it shows from inside."""
	p = Part( "bacta_pod_glass" )
	p.cyl( "pod_glass", GLASS_BOTTOM, GLASS_TOP, GLASS_R, 32, open_ends=True )
	for z in ( GLASS_BOTTOM + 30, GLASS_BOTTOM + 70 ):
		p.cyl( "pod_steel", z, z + 1.2, GLASS_R + 0.4, 32, open_ends=True )     # reinforcing bands
	return p.build( double_sided=True )


def liquid():
	"""The bacta: a column 1 unit tall from the tank floor, scaled up to fill (the game scales it on Z)."""
	p = Part( "bacta_pod_liquid" )
	p.cyl( "pod_bacta", 0, 1, GLASS_R - 1.5, 32 )
	return p.build( double_sided=True )


