def export( obj, boxes=() ):
	os.makedirs( MODEL_DIR, exist_ok=True )
	name = obj.name
	fbx = f"{name}_{REV}"
	bpy.ops.object.select_all( action="DESELECT" )
	obj.select_set( True )
	bpy.ops.export_scene.fbx( filepath=os.path.join( MODEL_DIR, fbx + ".fbx" ), use_selection=True, mesh_smooth_type="FACE",
		axis_forward="Y", axis_up="Z" )
	meta = os.path.join( MODEL_DIR, fbx + ".fbx.meta" )
	if not os.path.exists( meta ):
		with open( meta, "w", newline="\n" ) as fh:
			fh.write( '{\n  "guid": "%s"\n}' % uuid.uuid4() )
	physics = ""
	if boxes:
		physics = """
			{
				_class = "PhysicsShapeList"
				children =
				[""" + "".join( PHYS_BOX % ( c + s ) for c, s in boxes ) + """
				]
			},"""
	with open( os.path.join( MODEL_DIR, name + ".vmdl" ), "w", newline="\n" ) as fh:
		fh.write( VMDL % { "fbx": fbx, "physics": physics } )
	revs = sorted( ( f for f in os.listdir( MODEL_DIR ) if f.startswith( name + "_" ) and f.endswith( ".fbx" ) ),
		key=lambda f: os.path.getmtime( os.path.join( MODEL_DIR, f ) ) )
	for old in revs[:-2]:
		for fn in ( old, old + ".meta" ):
			try:
				os.remove( os.path.join( MODEL_DIR, fn ) )
			except OSError:
				pass


def main():
	bpy.ops.wm.read_factory_settings( use_empty=True )
	write_materials()
	# the frame collides with its plinth (you stand on it inside), the spine, the cap and the panel post; the glass and
	# the bacta never collide (the game keeps you in while the tank is shut)
	export( frame(), (
		( ( 0, 0, 6 ), ( 76, 76, 12 ) ),
		( ( -36, 0, 64 ), ( 12, 26, 128 ) ),
		( ( 0, 0, 120 ), ( 66, 66, 16 ) ),
		( ( 44, 0, 22 ), ( 10, 18, 44 ) ),
	) )
	export( glass() )
	export( liquid() )
	print( "BACTA POD models written" )


main()
