import os
import sys
import uuid

import bpy

HERE = os.path.dirname( os.path.abspath( __file__ ) )
PROJECT = os.path.dirname( HERE )
sys.path.insert( 0, HERE )
sys.path.insert( 0, os.path.join( PROJECT, "MapSource" ) )
import bf2_props as bp                      # VMDL template, REV
from source_mdl import load_model

SRC = r"X:\SWRP Projects\TFA_Extracted\props"
OUT = os.path.join( PROJECT, "Assets", "models", "medbay" )
MAT = os.path.join( PROJECT, "Assets", "materials", "medbay" )

_gt = open( os.path.join( PROJECT, "MapSource", "gmod_textures.py" ), encoding="utf-8" ).read()
_ns = { "__file__": os.path.join( PROJECT, "MapSource", "gmod_textures.py" ), "__name__": "gmod_textures_helpers" }
exec( compile( _gt[:_gt.index( "\ndef main(" )], "gmod_textures.py", "exec" ), _ns )
read_vtf, write_png = _ns["read_vtf"], _ns["write_png"]

TEX = os.path.join( SRC, "materials", "lordtrilobite", "starwars", "props" )


def frame_material():
	os.makedirs( MAT, exist_ok=True )
	rgba, _ = read_vtf( os.path.join( TEX, "tx_bactatank01.vtf" ) )
	write_png( os.path.join( MAT, "tank_color.png" ), rgba[..., :4].copy(), alpha=False )
	nrm, _ = read_vtf( os.path.join( TEX, "tx_bactatank01_nrm.vtf" ) )
	write_png( os.path.join( MAT, "tank_normal.png" ), nrm[..., :4].copy(), alpha=False )
	with open( os.path.join( MAT, "tank_frame.vmat" ), "w", newline="\n" ) as fh:
		fh.write( """// Generated by ModelSource/medbay_tank.py (LordTrilobite's bacta tank texture; local only)

Layer0
{
	shader "shaders/complex.shader"

	g_flModelTintAmount "1.000"
	g_vColorTint "[1.000000 1.000000 1.000000 0.000000]"
	TextureColor "materials/medbay/tank_color.png"
	TextureNormal "materials/medbay/tank_normal.png"
	TextureRoughness "[0.380000 0.380000 0.380000 0.000000]"
	g_flMetalness "0.350"
}
""" )
	with open( os.path.join( MAT, "tank_glass.vmat" ), "w", newline="\n" ) as fh:
		fh.write( """// Generated by ModelSource/medbay_tank.py: the tank's glass (the stock refracting glass shader, a faint cool tint)

Layer0
{
	shader "shaders/glass.shader"

	F_GLASS_QUALITY 0
	F_RENDER_BACKFACES 1

	TextureColor "[0.900000 0.950000 1.000000 1.000000]"
	TextureRoughness "[0.040000 0.040000 0.040000 0.000000]"
	TextureNormal "materials/default/default_normal.tga"
	g_flRefractionStrength "1.010"
	g_flBlurAmount "0.000"
}
""" )


def build( name, mdl, vmat ):
	m = load_model( os.path.join( SRC, mdl ) )
	verts, faces, uvs = [], [], []
	for tex, ps, ns, tuv in m.tris:
		b = len( verts )
		verts += [tuple( p ) for p in ps]
		faces.append( ( b, b + 1, b + 2 ) )
		uvs.append( tuv )
	me = bpy.data.meshes.new( name )
	me.from_pydata( verts, [], faces )
	uvl = me.uv_layers.new()
	for i, poly in enumerate( me.polygons ):
		for k, li in enumerate( poly.loop_indices ):
			u, v = uvs[i][k]
			uvl.data[li].uv = ( u, 1.0 - v )
	me.materials.append( bpy.data.materials.new( vmat ) )
	me.validate()
	ob = bpy.data.objects.new( name, me )
	bpy.context.scene.collection.objects.link( ob )
	bpy.ops.object.select_all( action="DESELECT" )
	ob.select_set( True )
	bpy.context.view_layer.objects.active = ob
	fbx = f"{name}_{bp.REV}"
	bpy.ops.export_scene.fbx( filepath=os.path.join( OUT, fbx + ".fbx" ), use_selection=True, mesh_smooth_type="FACE", axis_forward="Y", axis_up="Z" )
	with open( os.path.join( OUT, fbx + ".fbx.meta" ), "w", newline="\n" ) as fh:
		fh.write( '{\n  "guid": "%s"\n}' % uuid.uuid4() )
	with open( os.path.join( OUT, name + ".vmdl" ), "w", newline="\n" ) as fh:
		fh.write( bp.VMDL % { "fbx": f"models/medbay/{fbx}.fbx", "extra": "" } )
	revs = sorted( ( f for f in os.listdir( OUT ) if f.startswith( name + "_" ) and f.endswith( ".fbx" ) ),
		key=lambda f: os.path.getmtime( os.path.join( OUT, f ) ) )
	for old in revs[:-2]:
		for fn in ( old, old + ".meta" ):
			try:
				os.remove( os.path.join( OUT, fn ) )
			except OSError:
				pass
	print( f"TANK {name}: {len( me.polygons )} faces" )
	bpy.data.objects.remove( ob, do_unlink=True )


def main():
	bpy.ops.wm.read_factory_settings( use_empty=True )
	frame_material()
	build( "tank_frame", "models/lordtrilobite/starwars/props/bactatank.mdl", "materials/medbay/tank_frame.vmat" )
	build( "tank_glass", "models/lordtrilobite/starwars/props/bactatankb.mdl", "materials/medbay/tank_glass.vmat" )


if __name__ == "__main__":
	main()
