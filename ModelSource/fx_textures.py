def steam( size=128 ):
	"""A soft, lumpy puff of steam: white, its alpha a noisy round falloff."""
	y, x = np.mgrid[0:size, 0:size].astype( np.float32 )
	c = ( size - 1 ) / 2
	dx, dy = ( x - c ) / c, ( y - c ) / c
	r = np.sqrt( dx * dx + dy * dy )
	ang = np.arctan2( dy, dx )
	edge = 0.78 + sum( rng.uniform( 0.03, 0.08 ) * np.sin( k * ang + rng.uniform( 0, 6.28 ) ) for k in ( 2, 3, 5, 7 ) )
	soft = np.clip( 1 - r / edge, 0, 1 ) ** 1.8
	# billowy lumps: a few blurred blobs of random brightness
	lumps = np.zeros( ( size, size ), np.float32 )
	for _ in range( 14 ):
		bx, by = rng.uniform( 0.2, 0.8, 2 ) * size
		br = rng.uniform( 0.08, 0.22 ) * size
		lumps += rng.uniform( 0.4, 1.0 ) * np.exp( -( ( x - bx ) ** 2 + ( y - by ) ** 2 ) / ( 2 * br * br ) )
	lumps = lumps / lumps.max()
	alpha = np.clip( soft * ( 0.45 + 0.55 * lumps ), 0, 1 ) * 0.85
	col = np.ones( ( size, size, 3 ), np.float32 ) * ( 0.82 + 0.18 * lumps[..., None] )
	return ( np.clip( np.dstack( [col, alpha] ), 0, 1 ) * 255 ).astype( np.uint8 )


