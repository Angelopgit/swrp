def scanlines( w=4, h=4 ):
	"""A tiny tile of faint dark scanlines (one dark row in four), repeated over the screen."""
	img = np.zeros( ( h, w, 4 ), np.float32 )
	img[0, :, 3] = 0.09
	img[1, :, 3] = 0.03
	return ( img * 255 ).astype( np.uint8 )


def bubble( size=32 ):
	"""A little bubble: a thin bright rim with a highlight, clear in the middle (the bacta pods)."""
	y, x = np.mgrid[0:size, 0:size].astype( np.float32 )
	c = ( size - 1 ) / 2
	r = np.sqrt( ( x - c ) ** 2 + ( y - c ) ** 2 ) / c
	rim = np.exp( -( ( r - 0.82 ) / 0.1 ) ** 2 )
	hl = np.exp( -( ( x - c * 0.6 ) ** 2 + ( y - c * 0.6 ) ** 2 ) / ( 2 * ( c * 0.16 ) ** 2 ) )
	alpha = np.clip( rim * 0.8 + hl * 0.9 + 0.08 * ( r < 0.8 ), 0, 1 )
	col = np.ones( ( size, size, 3 ), np.float32 )
	return ( np.clip( np.dstack( [col, alpha] ), 0, 1 ) * 255 ).astype( np.uint8 )


def glow( size=64 ):
	"""A soft round glow: white, its alpha a smooth falloff with a brighter core (bolt flashes and impacts)."""
	y, x = np.mgrid[0:size, 0:size].astype( np.float32 )
	c = ( size - 1 ) / 2
	r = np.sqrt( ( x - c ) ** 2 + ( y - c ) ** 2 ) / c
	alpha = np.clip( np.exp( -( r / 0.38 ) ** 2 ) * 0.8 + np.exp( -( r / 0.12 ) ** 2 ) * 0.6, 0, 1 ) * ( r < 1 )
	col = np.ones( ( size, size, 3 ), np.float32 )
	return ( np.clip( np.dstack( [col, alpha] ), 0, 1 ) * 255 ).astype( np.uint8 )


write_png( os.path.join( OUT, "scanlines.png" ), scanlines() )
write_png( os.path.join( OUT, "glow.png" ), glow() )
write_png( os.path.join( OUT, "bubble.png" ), bubble() )
print( "FX scanlines and bubble written" )
