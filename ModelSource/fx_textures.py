"""
Procedural textures for effects (original, generated here): the blaster scorch mark and a puff of steam.

    "C:\\Program Files\\Blender Foundation\\Blender 5.2\\blender.exe" -b --factory-startup -P ModelSource/fx_textures.py

Writes Assets/materials/fx/scorch.png and scorch.vmat (translucent, used by SwrpFx for impact marks) and steam.png /
steam.vmat (the puffs from the steam vents, SwrpLivingShip), the helmet visor's scanline tile (scanlines.png) and the bacta pods' bubble (bubble.png).
"""
import os
import zlib
import struct
import numpy as np

HERE = os.path.dirname( os.path.abspath( __file__ ) )
OUT = os.path.join( os.path.dirname( HERE ), "Assets", "materials", "fx" )
os.makedirs( OUT, exist_ok=True )
rng = np.random.default_rng( 212 )


def write_png( path, rgba ):
	h, w, _ = rgba.shape
	raw = b"".join( b"\x00" + rgba[y].tobytes() for y in range( h ) )
	def chunk( tag, data ):
		return struct.pack( ">I", len( data ) ) + tag + data + struct.pack( ">I", zlib.crc32( tag + data ) & 0xffffffff )
	png = b"\x89PNG\r\n\x1a\n" + chunk( b"IHDR", struct.pack( ">IIBBBBB", w, h, 8, 6, 0, 0, 0 ) ) + chunk( b"IDAT", zlib.compress( raw, 9 ) ) + chunk( b"IEND", b"" )
	open( path, "wb" ).write( png )


def scorch( size=128 ):
	y, x = np.mgrid[0:size, 0:size].astype( np.float32 )
	c = ( size - 1 ) / 2
	dx, dy = ( x - c ) / c, ( y - c ) / c
	r = np.sqrt( dx * dx + dy * dy )
	ang = np.arctan2( dy, dx )
	# ragged edge: a few angular harmonics with random phase
	edge = 0.62 + sum( rng.uniform( 0.02, 0.07 ) * np.sin( k * ang + rng.uniform( 0, 6.28 ) ) for k in ( 3, 5, 7, 11, 17 ) )
	alpha = np.clip( ( edge - r ) / 0.25, 0, 1 ) ** 1.4
	# speckle and streaks radiating out
	streak = np.clip( np.sin( ang * 23 + rng.uniform( 0, 6.28 ) ) * 0.5 + 0.5, 0, 1 ) ** 6 * np.clip( 1 - r, 0, 1 )
	speck = rng.random( ( size, size ) ).astype( np.float32 )
	alpha = np.clip( alpha * ( 0.75 + 0.25 * speck ) + streak * 0.35, 0, 1 )
	# glowing-hot rim colour is not baked in; the mark is soot: near black with a faint brown edge
	col = np.zeros( ( size, size, 3 ), np.float32 )
	col[..., 0] = 0.05 + 0.10 * np.clip( r, 0, 1 )
	col[..., 1] = 0.04 + 0.06 * np.clip( r, 0, 1 )
	col[..., 2] = 0.035 + 0.03 * np.clip( r, 0, 1 )
	rgba = np.dstack( [col, alpha] )
	return ( np.clip( rgba, 0, 1 ) * 255 ).astype( np.uint8 )


img = scorch()
write_png( os.path.join( OUT, "scorch.png" ), img )
mask = img.copy()
mask[..., 0] = mask[..., 1] = mask[..., 2] = img[..., 3]
mask[..., 3] = 255
write_png( os.path.join( OUT, "scorch_mask.png" ), mask )
