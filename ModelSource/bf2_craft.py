"""
The flyable Republic craft from Battlefront II (2017), out of the local extraction in X:\\SWRP Projects\\BF2_Extracted: the
LAAT/i gunship and the ARC-170 (and the V-wing, not flyable yet). LOCAL ONLY: never publish or commit (CLAUDE.md, IP rules).

    "C:\\Program Files\\Blender Foundation\\Blender 5.2\\blender.exe" -b --factory-startup -P ModelSource/bf2_craft.py

Ship space, as the flight code expects it (Code/Flight/FlightCraft.cs): x forward (the nose), y left, z up, in map units
(inches, 1:1 with the films' sizes as BF2 has them), z = 0 at the bottom of the landing gear, centred on x and y. BF2 has
the nose towards -Y. Decal sheets are left out (they need their own blend mode); glass becomes the tinted canopy glass.
Prints each craft's bounds and the centres of its glass pieces (the cockpits), which CraftRegistry's seats use.
Writes Assets/models/craft/<name>_<rev>.fbx (+ .meta; keeps the previous revision), <name>.vmdl, vmats and textures.
"""
import os
import sys
import uuid

import bpy
from mathutils import Vector, Matrix

HERE = os.path.dirname( os.path.abspath( __file__ ) )
sys.path.insert( 0, HERE )
import bf2_props as bp

OUT = os.path.join( bp.ASSETS, "models", "craft" )
CRAFT = [
	( "laat", "Vehicle_LAAT/vehicle_air_laat_gunship_mesh.fbx" ),
	( "arc170", "Vehicle_ARC170/vehicle_air_arc170_static_donotuse_mesh.fbx" ),
	( "vwing", "Vehicle_VWing/vehicle_air_vwing_static_donotuse_mesh.fbx" ),
]
SKIP = ( "decal", )
GLASS_VMAT = "models/craft/bf2tex/canopy_glass.vmat"


def write_glass():
	os.makedirs( os.path.join( OUT, "bf2tex" ), exist_ok=True )
	with open( os.path.join( bp.ASSETS, GLASS_VMAT ), "w", newline="\n" ) as fh:
		fh.write( "\n".join( [
			"// Generated by ModelSource/bf2_craft.py: cockpit glass", "", "Layer0", "{", '\tshader "shaders/complex.shader"', "",
			"\tF_TRANSLUCENT 1", "", '\tg_flModelTintAmount "1.000"', '\tg_vColorTint "[0.30000 0.38000 0.46000 0.000000]"',
			'\tTextureColor "materials/default/default_color.tga"', '\tTextureNormal "materials/default/default_normal.tga"',
			'\tTextureRoughness "materials/default/default_rough.tga"', '\tTextureAmbientOcclusion "materials/default/default_ao.tga"',
			'\tg_flMetalness "0.400"', '\tg_flRoughnessScaleFactor "0.050"', '\tg_bFogEnabled "1"',
			'\tg_flOpacityScale "0.600"', '\tTextureTranslucency "[1.000000 1.000000 1.000000 0.000000]"', "}", "" ] ) )


def build( name, src ):
	fbx = os.path.join( bp.BF2, src )
	objs = bp.import_lod0( fbx )
	for o in list( objs ):
		if any( s in o.name.lower() for s in SKIP ):
			objs.remove( o )
			bpy.data.objects.remove( o, do_unlink=True )
	# rigid hulls: no skin weights (BF2's PART_* bone groups left in the FBX made ModelDoc bend the ARC-170's left wing cannon down
	# to the deck, 2026-10-12)
	for o in objs:
		o.vertex_groups.clear()
	# the craft's colour textures follow the second UV set (UVChannel1); the first is a tiling/detail layout that scrambles the
	# hull into atlas patches (Angelo, 2026-10-12). The vmdl reads the first set, so the second goes first and the rest go.
	for o in objs:
		uvs = o.data.uv_layers
		if len( uvs ) > 1:
			data = [0.0] * ( len( uvs[1].data ) * 2 )
			uvs[1].data.foreach_get( "uv", data )
			uvs[0].data.foreach_set( "uv", data )
			while len( uvs ) > 1:
				uvs.remove( uvs[1] )
	# nose -Y -> +X, left = +X(BF2), up Z; metres -> inches
	rot = Matrix( ( ( 0, -1, 0 ), ( 1, 0, 0 ), ( 0, 0, 1 ) ) ).to_4x4()
	for o in objs:
		o.data.transform( Matrix.Scale( bp.M, 4 ) @ rot )
	lo, hi = bp.bounds( objs )
	shift = Vector( ( -( lo.x + hi.x ) / 2, -( lo.y + hi.y ) / 2, -lo.z ) )
	for o in objs:
		o.data.transform( Matrix.Translation( shift ) )
	lo, hi = bp.bounds( objs )
	texdir_src = os.path.join( os.path.dirname( fbx ), "Textures" )
	textures = [f for f in os.listdir( texdir_src ) if f.lower().endswith( "_cs.png" )]
	tex_dir = os.path.join( OUT, "bf2tex" )
	glass_centres = []
	for o in objs:
		low = o.name.lower()
		if "glass" in low:
			mat_rel = GLASS_VMAT
			# each separate glass piece's centre (the cockpits)
			import bmesh
			bm = bmesh.new()
			bm.from_mesh( o.data )
			bm.verts.ensure_lookup_table()
			seen = set()
			for v in bm.verts:
				if v.index in seen:
					continue
				stack, island = [v], []
				seen.add( v.index )
				while stack:
					x = stack.pop()
					island.append( x.co.copy() )
					for e in x.link_edges:
						w = e.other_vert( x )
						if w.index not in seen:
							seen.add( w.index )
							stack.append( w )
				if len( island ) >= 12:
					c = sum( island, Vector() ) / len( island )
					size = max( ( p - c ).length for p in island )
					glass_centres.append( ( round( c.x ), round( c.y ), round( c.z ), round( size ) ) )
			bm.free()
		else:
			key = low.replace( "_", "" )
			best = max( textures, key=lambda t: sum( 1 for k in range( len( key ) - 2 ) if key[k:k + 3] in t.lower().replace( "_", "" ) ), default=None )
			stem = best[:-7] if best else None
			mat_name = f"{name}_{( stem or 'flat' ).lower()}"
			mat_rel = f"models/craft/bf2tex/{mat_name}.vmat"
			if not os.path.exists( os.path.join( bp.ASSETS, mat_rel ) ):
				cs, nrm = bp.texture_set( texdir_src, stem ) if stem else ( None, None )
				lines, metal = bp.convert_textures( cs, nrm, tex_dir, mat_name )
				bp.write_vmat( os.path.join( bp.ASSETS, mat_rel ), lines, metal )
		mat = bpy.data.materials.get( mat_rel ) or bpy.data.materials.new( mat_rel )
		o.data.materials.clear()
		o.data.materials.append( mat )
		print( f"BF2CRAFT {name} part {o.name}: {len( o.data.polygons )} faces -> {mat_rel}" )
	bpy.ops.object.select_all( action="DESELECT" )
	for o in objs:
		o.select_set( True )
	bpy.context.view_layer.objects.active = objs[0]
	if len( objs ) > 1:
		bpy.ops.object.join()
	ob = bpy.context.view_layer.objects.active
	ob.name = name
	fbx_name = f"{name}_{bp.REV}"
	bpy.ops.export_scene.fbx( filepath=os.path.join( OUT, fbx_name + ".fbx" ), use_selection=True, mesh_smooth_type="FACE", axis_forward="Y", axis_up="Z" )
	meta = os.path.join( OUT, fbx_name + ".fbx.meta" )
	if not os.path.exists( meta ):
		with open( meta, "w", newline="\n" ) as fh:
			fh.write( '{\n  "guid": "%s"\n}' % uuid.uuid4() )
	with open( os.path.join( OUT, name + ".vmdl" ), "w", newline="\n" ) as fh:
		fh.write( bp.VMDL % { "fbx": f"models/craft/{fbx_name}.fbx", "extra": "" } )
	revs = sorted( ( f for f in os.listdir( OUT ) if f.startswith( name + "_" ) and f.endswith( ".fbx" ) ), key=lambda f: os.path.getmtime( os.path.join( OUT, f ) ) )
	for old in revs[:-2]:
		for fn in ( old, old + ".meta" ):
			try:
				os.remove( os.path.join( OUT, fn ) )
			except OSError:
				pass
	print( f"BF2CRAFT {name}: {len( ob.data.polygons )} faces, size {[round( x ) for x in ( hi - lo )]} (inches), glass pieces (x, y, z, radius): {sorted( glass_centres, key=lambda g: -g[3] )[:8]}" )


def main():
	write_glass()
	only = sys.argv[sys.argv.index( "--" ) + 1:] if "--" in sys.argv else []
	for name, src in CRAFT:
		if not only or name in only:
			build( name, src )


main()
