"""
Original textures and materials for the Jedi lightsaber system (Code/Jedi). Plain Python, no numpy:

    python ModelSource/jedi_textures.py

Writes into Assets/materials/jedi/:
  hilt_palette.png + hilt.vmat + hilt_glow.vmat   the lightsaber hilts' own voxel palette (16x16 blocks of 16 px, the same
                                                  layout as materials/voxel/palette.png, so VoxelMesher can draw with it);
                                                  index numbers match SaberHilt.Colors in Code/Jedi/SaberHilt.cs
  saber_burn.png + saber_burn_mask.png + .vmat    a lightsaber cut in a wall or floor: a thin molten-edged groove with
                                                  a dark scorch either side, fading out at the ends
  force_ring.png                                  a soft ring (Force push shockwave, the Force wheel's glow)
"""
import math
import os
import struct
import zlib

PROJECT = os.path.join( os.path.dirname( os.path.abspath( __file__ ) ), ".." )
OUT = os.path.join( PROJECT, "Assets", "materials", "jedi" )
os.makedirs( OUT, exist_ok=True )


def png( path, w, h, rows, alpha=False ):
	raw = b"".join( b"\x00" + bytes( r ) for r in rows )
	def chunk( t, d ): return struct.pack( ">I", len( d ) ) + t + d + struct.pack( ">I", zlib.crc32( t + d ) & 0xffffffff )
	with open( path, "wb" ) as fh:
		fh.write( b"\x89PNG\r\n\x1a\n" + chunk( b"IHDR", struct.pack( ">IIBBBBB", w, h, 8, 6 if alpha else 2, 0, 0, 0 ) )
			+ chunk( b"IDAT", zlib.compress( raw, 9 ) ) + chunk( b"IEND", b"" ) )
	print( os.path.relpath( path, PROJECT ) )


