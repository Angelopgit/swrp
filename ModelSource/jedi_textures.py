# ----- the burn: 256 x 64, the cut runs along x -----
def hash2( x, y ):
	h = ( x * 374761393 + y * 668265263 ) & 0xffffffff
	h = ( ( h ^ ( h >> 13 ) ) * 1274126177 ) & 0xffffffff
	return ( h & 0xffff ) / 65535.0


def smooth_noise( x, y ):
	x0, y0 = int( math.floor( x ) ), int( math.floor( y ) )
	fx, fy = x - x0, y - y0
	fx, fy = fx * fx * ( 3 - 2 * fx ), fy * fy * ( 3 - 2 * fy )
	a, b = hash2( x0, y0 ), hash2( x0 + 1, y0 )
	c, d = hash2( x0, y0 + 1 ), hash2( x0 + 1, y0 + 1 )
	return ( a + ( b - a ) * fx ) * ( 1 - fy ) + ( c + ( d - c ) * fx ) * fy


W, H = 256, 64
color_rows, mask_rows = [], []
for y in range( H ):
	crow, mrow = [], []
	v = ( y + 0.5 ) / H * 2 - 1                                       # -1..1 across the cut
	for x in range( W ):
		u = ( x + 0.5 ) / W                                           # 0..1 along it
		ends = min( 1.0, min( u, 1 - u ) / 0.12 )                     # fade in and out at the ends
		wobble = ( smooth_noise( u * 18, 3.1 ) - 0.5 ) * 0.18
		d = abs( v - wobble )
		n = smooth_noise( u * 40, y * 0.35 ) * 0.6 + smooth_noise( u * 90, y * 0.9 ) * 0.4
		groove = max( 0.0, 1 - d / 0.16 )                             # the cut itself
		scorch = max( 0.0, 1 - d / ( 0.75 + n * 0.25 ) ) ** 1.4        # soot either side
		alpha = min( 1.0, groove * 1.0 + scorch * ( 0.55 + 0.35 * n ) ) * ends
		# colour: near-black groove with a dull cooled-slag rim, brown-black soot outside
		rim = max( 0.0, 1 - abs( d - 0.17 ) / 0.07 )
		r = 14 + 40 * rim + 30 * ( 1 - groove ) * scorch * n
		g = 12 + 24 * rim + 22 * ( 1 - groove ) * scorch * n
		b = 11 + 12 * rim + 16 * ( 1 - groove ) * scorch * n
		crow += [int( min( 255, r ) ), int( min( 255, g ) ), int( min( 255, b ) )]
		m = int( max( 0.0, min( 1.0, alpha ) ) * 255 )
		mrow += [m, m, m]
	color_rows.append( crow )
	mask_rows.append( mrow )
png( os.path.join( OUT, "saber_burn.png" ), W, H, color_rows )
png( os.path.join( OUT, "saber_burn_mask.png" ), W, H, mask_rows )
with open( os.path.join( OUT, "saber_burn.vmat" ), "w", newline="\n" ) as fh:
	fh.write( HEAD + "\n\tF_TRANSLUCENT 1\n\n"
		'\tg_flModelTintAmount "1.000"\n\tg_vColorTint "[1.000000 1.000000 1.000000 0.000000]"\n'
		'\tTextureColor "materials/jedi/saber_burn.png"\n\tTextureTranslucency "materials/jedi/saber_burn_mask.png"\n'
		'\tTextureNormal "materials/default/default_normal.tga"\n\tTextureRoughness "materials/default/default_rough.tga"\n'
		'\tg_flMetalness "0.000"\n\tg_flOpacityScale "1.000"\n}\n' )
print( "saber_burn.vmat" )

# ----- a soft ring, white with alpha (tinted in code) -----
S = 128
ring = []
for y in range( S ):
	row = []
	for x in range( S ):
		dx, dy = ( x + 0.5 ) / S * 2 - 1, ( y + 0.5 ) / S * 2 - 1
		r = math.sqrt( dx * dx + dy * dy )
		a = math.exp( -( ( r - 0.78 ) / 0.09 ) ** 2 ) + 0.25 * math.exp( -( ( r - 0.6 ) / 0.22 ) ** 2 )
		a = max( 0.0, min( 1.0, a ) ) * ( 1.0 if r < 1 else 0.0 )
		row += [255, 255, 255, int( a * 255 )]
	ring.append( row )
png( os.path.join( OUT, "force_ring.png" ), S, S, ring, alpha=True )
