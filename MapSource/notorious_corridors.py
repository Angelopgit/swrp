def write_materials( project ):
	out = os.path.join( project, "Assets", "materials", "corridor" )
	os.makedirs( out, exist_ok=True )
	for _, ( name, prefix, emissive ) in SETS.items():
		tex = {}
		for f in os.listdir( KIT_TEX ):
			if not f.startswith( prefix ):
				continue
			kind = f[len( prefix ):].lstrip( "_" ).rsplit( ".", 1 )[0].lower()      # basecolor, metallic, roughness, normal, emissive
			dst = f"{name}_{kind}.png"
			if not os.path.exists( os.path.join( out, dst ) ):
				shutil.copyfile( os.path.join( KIT_TEX, f ), os.path.join( out, dst ) )
			tex[kind] = f"{MAT_DIR_REL}/{dst}"
		lines = [
			"// Generated by MapSource/notorious_corridors.py: Venator corridor kit (Corridor Prefab, local only)", "", "Layer0", "{",
			'\tshader "shaders/complex.shader"', "",
		]
		if emissive and "emissive" in tex:
			lines.append( "\tF_SELF_ILLUM 1" )
		lines.append( "\tF_METALNESS_TEXTURE 1" )
		lines += [
			"", '\tg_flModelTintAmount "1.000"', '\tg_vColorTint "[1.000000 1.000000 1.000000 0.000000]"',
			f'\tTextureColor "{tex["basecolor"]}"',
			f'\tTextureNormal "{tex["normal"]}"',
			f'\tTextureRoughness "{tex["roughness"]}"',
			f'\tTextureMetalness "{tex["metallic"]}"',
			'\tTextureAmbientOcclusion "materials/default/default_ao.tga"',
			'\tg_flRoughnessScaleFactor "1.000"', '\tg_bFogEnabled "1"',
		]
		if emissive and "emissive" in tex:
			lines += [
				'\tg_flSelfIllumAlbedoFactor "0.000"', '\tg_flSelfIllumBrightness "4.000"', '\tg_flSelfIllumScale "1.000"',
				'\tg_vSelfIllumTint "[0.92000 0.96000 1.00000 0.000000]"', f'\tTextureSelfIllumMask "{tex["emissive"]}"',
			]
		lines.append( "}" )
		with open( os.path.join( out, name + ".vmat" ), "w", newline="\n" ) as fh:
			fh.write( "\n".join( lines ) + "\n" )


def vmat( kit_material ):
	for k, ( name, _, _ ) in SETS.items():
		if kit_material.startswith( k ):
			return f"{MAT_DIR_REL}/{name}.vmat"
	return f"{MAT_DIR_REL}/wall_panels.vmat"


