class Kit:
	def __init__( self ):
		self.tris = collections.defaultdict( list )      # chunk -> [(vmat, verts, uvs)]
		self.boxes = collections.defaultdict( list )     # chunk -> [(min, max)]
		self.lights = []

	@staticmethod
	def chunk( p ):
		# no minus signs: a '-' in a model's node name breaks ModelDoc's physics node lookup ("resolve failure")
		return "_".join( str( int( v // 2048 ) ).replace( "-", "m" ) for v in p[:3] )

	def add( self, mod, origin, ex, ey, ez ):
		"""Local (x, y, z) metres -> origin + x*ex + y*ey + z*ez (units per metre in each)."""
		key = self.chunk( origin )
		flip = ( ex.cross( ey ).dot( ez ) < 0 ) != mod.mirrored
		for ( mat, vs, uvs ) in mod.tris:
			w = [tuple( origin + ex * p[0] + ey * p[1] + ez * p[2] ) for p in vs]
			if flip:
				w = [w[0], w[2], w[1]]
				uvs = [uvs[0], uvs[2], uvs[1]]
			self.tris[key].append( ( mat, w, uvs ) )

	def box( self, a, b ):
		lo = tuple( min( a[i], b[i] ) for i in range( 3 ) )
		hi = tuple( max( a[i], b[i] ) for i in range( 3 ) )
		self.boxes[self.chunk( ( ( lo[0] + hi[0] ) / 2, ( lo[1] + hi[1] ) / 2, ( lo[2] + hi[2] ) / 2 ) )].append( ( lo, hi ) )


def wall_axes( s, side ):
	plane = s.lo if side == "lo" else s.hi
	inward = s.C * ( 1 if side == "lo" else -1 )
	t_dir = ( -inward ).cross( UP )            # a wall module's +x
	return plane, inward, t_dir


def lay_wall( kit, mods, s, side, a, b, pillars ):
	"""Panels on one wall from a to b (along the corridor), with a pillar at each end flagged in pillars."""
	plane, inward, t_dir = wall_axes( s, side )
	sc = s.scale * M
	hz = s.wall_h / KIT_WALL_H
	pw = mods["WallPanel2"].width * sc
	inner = ( b - a ) - pw * ( pillars[0] + pillars[1] )
	if inner < 0.4 * mods["WallPanel3"].width * sc:
		pillars = ( False, False )
		inner = b - a
	unit = sum( mods[n].width for n in PATTERN ) * sc
	names = list( PATTERN )
	k = inner / unit if unit else 1.0
	if k < 0.6:
		n = max( 1, round( inner / ( mods["WallPanel3"].width * sc ) ) )
		names = ["WallPanel1" if i % 2 else "WallPanel3" for i in range( n )]
		k = inner / sum( mods[x].width * sc for x in names )
	elif k > 1.5:
		reps = max( 1, round( inner / unit ) )
		names = list( PATTERN ) * reps
		k = inner / ( unit * reps )
	seq = ( [( "WallPanel2", 1.0 )] if pillars[0] else [] ) + [( n, k ) for n in names] + ( [( "WallPanel2", 1.0 )] if pillars[1] else [] )
	forward = t_dir.dot( s.A ) > 0
	if not forward:
		seq.reverse()
	pos = a if forward else b
	sgn = 1 if forward else -1
	for name, kk in seq:
		m = mods[name]
		w = m.width * sc * kk
		origin = s.frame( pos, plane, 0 )
		ex, ey, ez = t_dir * ( sc * kk ), inward * sc, UP * hz
		kit.add( m, origin, ex, ey, ez )
		if name == "WallPanel2":
			kit.box( tuple( origin ), tuple( origin + ex * m.width + ey * m.hi[1] + ez * KIT_WALL_H ) )
		pos += sgn * w


def lay_pillar( kit, mods, s, side, a, b ):
	"""One pillar filling a to b on a wall, with its collision box."""
	plane, inward, t_dir = wall_axes( s, side )
	m = mods["WallPanel2"]
	forward = t_dir.dot( s.A ) > 0
	ex, ey, ez = t_dir * ( ( b - a ) / m.width ), inward * ( s.scale * M ), UP * ( s.wall_h / KIT_WALL_H )
	origin = s.frame( a if forward else b, plane, 0 )
	kit.add( m, origin, ex, ey, ez )
	kit.box( tuple( origin ), tuple( origin + ex * m.width + ey * m.hi[1] + ez * KIT_WALL_H ) )


def lay_door( kit, mods, s, side, a, b, top ):
	"""A kit door frame lining a doorway (opening fitted to it), and a panel from its top to the ceiling. Returns the frame's
	reach beyond the doorway on each side."""
	m = mods["Small_DoorFrame"]
	plane, inward, t_dir = wall_axes( s, side )
	kx = ( b - a ) / ( DOOR_OPEN_HI - DOOR_OPEN_LO )                 # units per metre
	kz = top / DOOR_OPEN_TOP
	if m.hi[2] * kz > s.wall_h:
		kz = s.wall_h / m.hi[2]
	reach = ( DOOR_OPEN_LO - DOOR_FRAME_LO ) * kx
	forward = t_dir.dot( s.A ) > 0
	o = s.frame( a - reach if forward else b + reach, plane, 0 )
	kit.add( m, o, t_dir * kx, inward * ( s.scale * M ), UP * kz )
	frame_top = m.hi[2] * kz
	frame_w = m.width * kx
	# collision for the frame's sides (it may stand a little proud of the wall)
	# panel above the frame
	gap = s.wall_h - frame_top
	if gap > 2:
		p = mods["WallPanel3"]
		kit.add( p, o + UP * frame_top, t_dir * ( frame_w / p.width ), inward * ( s.scale * M ), UP * ( gap / p.hi[2] ) )
	return reach


def lay_spans( kit, mods, s, t0, t1, bulk_at ):
	"""Ceiling light panels wall to wall from t0 to t1, and bulkhead frames at bulk_at."""
	sc = s.scale * M
	hz = s.wall_h / KIT_WALL_H
	width = s.hi - s.lo
	ceil = mods["VenatorLight"]
	n = max( 1, round( ( t1 - t0 ) / ( ceil.width * sc ) ) )
	pitch = ( t1 - t0 ) / n
	ex = s.A * ( pitch / ceil.width )
	across, base = s.C * ( width / ceil.hi[1] ), s.lo
	if ex.cross( across ).dot( UP ) < 0:
		across, base = -across, s.hi
	for i in range( n ):
		kit.add( ceil, s.frame( t0 + i * pitch, base, 0 ), ex, across, UP * hz )
		if i % max( 1, round( LIGHT_EVERY / pitch ) ) == 0:
			kit.lights.append( tuple( s.frame( t0 + ( i + 0.5 ) * pitch, ( s.lo + s.hi ) / 2, s.wall_h - 14 ) ) )
	bulk = mods["LargeDoorFrame"]
	b_across, b_base = s.C * ( width / bulk.hi[1] ), s.lo
	if ( s.A ).cross( b_across ).dot( UP ) < 0:
		b_across, b_base = -b_across, s.hi
	depth = bulk.width * sc
	jl = ( BULK_OPEN_LO - BULK_LO ) / ( BULK_HI - BULK_LO ) * width
	jr = ( BULK_HI - BULK_OPEN_HI ) / ( BULK_HI - BULK_LO ) * width
	for t in bulk_at:
		kit.add( bulk, s.frame( t - depth / 2, b_base, 0 ), s.A * sc, b_across, UP * hz )
		a, b = t - depth / 2, t + depth / 2
		for ( c0, c1, z0, z1 ) in ( ( s.lo, s.lo + jl, 0, s.wall_h ), ( s.hi - jr, s.hi, 0, s.wall_h ), ( s.lo, s.hi, BULK_HEAD * hz, s.wall_h ) ):
			kit.box( tuple( s.frame( a, c0, z0 ) ), tuple( s.frame( b, c1, z1 ) ) )


def lay_segment( kit, mods, s, bvh ):
	r = wall_runs( s, bvh )
	spans = [x for side in r for x in r[side][0]]
	if not spans:
		return False
	t0 = min( a for a, _ in spans )
	t1 = max( b for _, b in spans )
	sc = s.scale * M
	pw = mods["WallPanel2"].width * sc
	depth = mods["LargeDoorFrame"].width * sc
	doors = [( a, b ) for side in r for ( a, b, _ ) in r[side][1]]
	# bulkheads every BULK_EVERY metres, kept clear of doorways and of the ends
	bulk = []
	n = int( ( t1 - t0 ) // ( BULK_EVERY * M ) )
	for i in range( 1, n + 1 ):
		t = t0 + i * ( t1 - t0 ) / ( n + 1 )
		if all( t + pw + 8 < a or t - pw - 8 > b for ( a, b ) in doors ):
			bulk.append( t )
	s.runs = {}
	for side in ( "lo", "hi" ):
		walls, doorways = r[side]
		cuts = []
		for ( a, b, top ) in doorways:
			reach = lay_door( kit, mods, s, side, a, b, top )
			cuts.append( ( a - reach, b + reach, False ) )
		for t in bulk:
			cuts.append( ( t - pw, t + pw, True ) )       # two pillars back to back under the bulkhead
		for ( a, b ) in walls:
			pieces = [[a, b, True, True]]
			for ( ca, cb, pil ) in sorted( cuts ):
				nxt = []
				for p in pieces:
					if cb <= p[0] or ca >= p[1]:
						nxt.append( p )
						continue
					if ca > p[0]:
						nxt.append( [p[0], ca, p[2], False] )
					if cb < p[1]:
						nxt.append( [cb, p[1], False, p[3]] )
					lo_, hi_ = max( ca, p[0] ), min( cb, p[1] )
					if pil and hi_ - lo_ > pw * 1.5:
						lay_pillar( kit, mods, s, side, lo_, ( lo_ + hi_ ) / 2 )      # two pillars back to back under the bulkhead
						lay_pillar( kit, mods, s, side, ( lo_ + hi_ ) / 2, hi_ )
				pieces = nxt
			for ( pa, pb, ea, eb ) in pieces:
				if pb - pa >= 12:
					lay_wall( kit, mods, s, side, pa, pb, ( ea, eb ) )
		s.runs[side] = ( walls, doorways )
	lay_spans( kit, mods, s, t0, t1, [t for t in bulk if t0 + depth < t < t1 - depth] )
	s.t0, s.t1 = t0, t1
	return True


