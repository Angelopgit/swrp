class Module:
	def __init__( self, name, tris, lo, hi, mirrored ):
		self.name, self.tris, self.lo, self.hi = name, tris, lo, hi
		self.mirrored = mirrored  # the re-basing flipped an axis (winding must flip back)

	@property
	def width( self ):
		return self.hi[0] - self.lo[0]


def load_kit( scratch ):
	fbx = os.path.join( scratch, "VenatorV3Prefab.fbx" )
	if not os.path.exists( fbx ):
		with zipfile.ZipFile( KIT_ZIP ) as z:
			with z.open( "VenatorPrefab/VenatorV3Prefab.fbx" ) as src, open( fbx, "wb" ) as dst:
				shutil.copyfileobj( src, dst )
	before = set( bpy.data.objects )
	bpy.ops.import_scene.fbx( filepath=fbx )
	new = [o for o in bpy.data.objects if o not in before]
	raw = {}
	for o in new:
		if o.type != "MESH":
			continue
		# the busiest pieces (wall lights, door frames: 4000+ faces of tiny detail) are thinned, as they repeat thousands of times
		if len( o.data.polygons ) > 1500:
			dec = o.modifiers.new( "thin", "DECIMATE" )
			dec.ratio = 1200 / len( o.data.polygons )
			bpy.context.view_layer.objects.active = o
			bpy.ops.object.modifier_apply( modifier=dec.name )
		me = o.data
		me.calc_loop_triangles()
		uvl = me.uv_layers.active.data if me.uv_layers.active else None
		mw = o.matrix_world
		tris, pts = [], []
		for t in me.loop_triangles:
			mat = me.materials[t.material_index].name if me.materials and me.materials[t.material_index] else ""
			vs = [tuple( mw @ me.vertices[me.loops[l].vertex_index].co ) for l in t.loops]
			uvs = [tuple( uvl[l].uv ) if uvl else ( 0.0, 0.0 ) for l in t.loops]
			tris.append( ( vmat( mat ), vs, uvs ) )
			pts += vs
		lo = tuple( min( p[i] for p in pts ) for i in range( 3 ) )
		hi = tuple( max( p[i] for p in pts ) for i in range( 3 ) )
		raw[o.name] = ( tris, lo, hi )
	for o in new:
		bpy.data.objects.remove( o, do_unlink=True )
	return raw


def wall_module( name, raw ):
	"""A +Y wall piece (faces -Y): y becomes depth out of the wall into the corridor (a flip)."""
	tris, lo, hi = raw
	back = hi[1]
	t = [( mat, [( p[0] - lo[0], back - p[1], p[2] - KIT_FLOOR_Z ) for p in vs], uvs ) for ( mat, vs, uvs ) in tris]
	return Module( name, t, ( 0.0, 0.0, 0.0 ), ( hi[0] - lo[0], back - lo[1], hi[2] - KIT_FLOOR_Z ), True )


def span_module( name, raw ):
	"""Something spanning the corridor (ceiling panel, bulkhead): x along, y across from the kit's -Y wall."""
	tris, lo, hi = raw
	t = [( mat, [( p[0] - lo[0], p[1] - lo[1], p[2] - KIT_FLOOR_Z ) for p in vs], uvs ) for ( mat, vs, uvs ) in tris]
	return Module( name, t, ( 0.0, 0.0, 0.0 ), ( hi[0] - lo[0], hi[1] - lo[1], hi[2] - KIT_FLOOR_Z ), False )


def doorframe_module( name, raw ):
	"""The small door frame: flush with the +Y wall at its low-y side, lining the doorway into the wall. y = depth out of the
	wall (negative: into it)."""
	tris, lo, hi = raw
	face = lo[1]
	t = [( mat, [( p[0] - lo[0], face - p[1], p[2] - KIT_FLOOR_Z ) for p in vs], uvs ) for ( mat, vs, uvs ) in tris]
	return Module( name, t, ( 0.0, face - hi[1], 0.0 ), ( hi[0] - lo[0], 0.0, hi[2] - KIT_FLOOR_Z ), True )


