def box_faces( lo, hi ):
	x0, y0, z0 = lo
	x1, y1, z1 = hi
	return [
		( [( x0, y0, z0 ), ( x0, y1, z0 ), ( x1, y1, z0 ), ( x1, y0, z0 )], ( 0, 0, -1 ) ),
		( [( x0, y0, z1 ), ( x1, y0, z1 ), ( x1, y1, z1 ), ( x0, y1, z1 )], ( 0, 0, 1 ) ),
		( [( x0, y0, z0 ), ( x1, y0, z0 ), ( x1, y0, z1 ), ( x0, y0, z1 )], ( 0, -1, 0 ) ),
		( [( x0, y1, z0 ), ( x0, y1, z1 ), ( x1, y1, z1 ), ( x1, y1, z0 )], ( 0, 1, 0 ) ),
		( [( x0, y0, z0 ), ( x0, y0, z1 ), ( x0, y1, z1 ), ( x0, y1, z0 )], ( -1, 0, 0 ) ),
		( [( x1, y0, z0 ), ( x1, y1, z0 ), ( x1, y1, z1 ), ( x1, y0, z1 )], ( 1, 0, 0 ) ),
	]


def _meta( path ):
	if not os.path.exists( path ):
		with open( path, "w", newline="\n" ) as fh:
			fh.write( '{\n  "guid": "%s"\n}' % uuid.uuid4() )


def export( kit, build_object, prop_vmdl, prop_phys, rev, model_dir, project ):
	cdir = os.path.join( model_dir, "corridors" )
	os.makedirs( cdir, exist_ok=True )
	vm = prop_vmdl.replace( "models/notorious/props/", "models/notorious/corridors/" )
	pp = prop_phys.replace( "models/notorious/props/", "models/notorious/corridors/" )
	names = []
	for key, tris in sorted( kit.tris.items() ):
		name = f"corridor_{key}"
		fbx = f"{name}_{rev}"
		faces = []
		for ( mat, vs, uvs ) in tris:
			e1 = Vector( vs[1] ) - Vector( vs[0] )
			e2 = Vector( vs[2] ) - Vector( vs[0] )
			nn = e1.cross( e2 )
			nn = tuple( nn.normalized() ) if nn.length > 1e-9 else ( 0, 0, 1 )
			faces.append( ( mat, vs, nn, ( "uv", uvs ) ) )
		bpy.ops.object.select_all( action="DESELECT" )
		ob = build_object( fbx, faces )
		ob.select_set( True )
		bpy.ops.export_scene.fbx( filepath=os.path.join( cdir, fbx + ".fbx" ), use_selection=True, mesh_smooth_type="FACE", axis_forward="Y", axis_up="Z" )
		bpy.data.objects.remove( ob, do_unlink=True )
		_meta( os.path.join( cdir, fbx + ".fbx.meta" ) )
		physics = ""
		if kit.boxes.get( key ):
			pfbx = f"{fbx}_phys"
			pf = []
			for ( lo, hi ) in kit.boxes[key]:
				pf += [( "materials/notorious/phys.vmat", v, nn, 256 ) for ( v, nn ) in box_faces( lo, hi )]
			bpy.ops.object.select_all( action="DESELECT" )
			pb = build_object( pfbx, pf )
			pb.select_set( True )
			bpy.ops.export_scene.fbx( filepath=os.path.join( cdir, pfbx + ".fbx" ), use_selection=True, mesh_smooth_type="FACE", axis_forward="Y", axis_up="Z" )
			bpy.data.objects.remove( pb, do_unlink=True )
			_meta( os.path.join( cdir, pfbx + ".fbx.meta" ) )
			physics = pp % { "phys": pfbx }
		with open( os.path.join( cdir, name + ".vmdl" ), "w", newline="\n" ) as fh:
			fh.write( vm % { "fbx": fbx, "physics": physics } )
		names.append( f"models/notorious/corridors/{name}.vmdl" )
		revs = sorted( ( f for f in os.listdir( cdir ) if f.startswith( name + "_" ) and f.endswith( ".fbx" ) and not f.endswith( "_phys.fbx" ) ),
			key=lambda f: os.path.getmtime( os.path.join( cdir, f ) ) )
		for old in revs[:-2]:
			for fn in ( old, old + ".meta", old[:-4] + "_phys.fbx", old[:-4] + "_phys.fbx.meta" ):
				try:
					os.remove( os.path.join( cdir, fn ) )
				except OSError:
					pass
	with open( os.path.join( project, "Assets", "data", "notorious_corridors.json" ), "w", newline="\n" ) as fh:
		json.dump( names, fh, indent=1 )
	return names


_LOG = None


def log( msg ):
	"""Progress to MapSource/__pycache__/corridor_kit/progress.txt (Blender's stdout only arrives when it exits)."""
	import time
	if _LOG:
		with open( _LOG, "a" ) as fh:
			fh.write( time.strftime( "%H:%M:%S" ) + " " + msg + "\n" )


def apply( render, phys, rects, build_object, prop_vmdl, prop_phys, rev, model_dir, project, scratch ):
	"""Returns (restyled render faces, corridor light positions). Writes the kit chunk models, their list, and
	MapSource/corridors_debug.json (every corridor laid: walls, doorways, scale) for checking."""
	global _LOG
	os.makedirs( scratch, exist_ok=True )
	_LOG = os.path.join( scratch, "progress.txt" )
	open( _LOG, "w" ).close()
	log( f"start: {len( render )} render faces, {len( phys )} collision faces, {len( rects )} floor rects" )
	# the inputs, for MapSource/corridors_only.py (re-lays the corridors without rebuilding the whole map)
	import pickle
	with open( os.path.join( scratch, "inputs.pkl" ), "wb" ) as fh:
		pickle.dump( ( render, phys, rects ), fh )
	write_materials( project )
	raw = load_kit( scratch )
	mods = { n: wall_module( n, raw[n] ) for n in ( "WallPanel1", "WallPanel2", "WallPanel3", "WallPanel4", "VenatorLights" ) }
	mods["VenatorLight"] = span_module( "VenatorLight", raw["VenatorLight"] )
	mods["LargeDoorFrame"] = span_module( "LargeDoorFrame", raw["LargeDoorFrame"] )
	mods["Small_DoorFrame"] = doorframe_module( "Small_DoorFrame", raw["Small_DoorFrame"] )
	bvh = make_bvh( phys )
	log( "kit loaded, bvh built" )
	segs = find_segments( rects, bvh )
	log( f"{len( segs )} corridors found" )
	kit = Kit()
	laid = []
	for i, s in enumerate( segs ):
		if lay_segment( kit, mods, s, bvh ):
			laid.append( s )
		if i % 10 == 0:
			log( f"laid {i + 1}/{len( segs )}, {sum( len( t ) for t in kit.tris.values() )} tris" )
	render, stats = restyle( render, laid )
	log( f"restyled: {dict( stats )}" )
	names = export( kit, build_object, prop_vmdl, prop_phys, rev, model_dir, project )
	log( f"exported {len( names )} chunks" )
	dbg = [{
		"axis": "xy"[s.ax], "z": s.z, "lo": s.lo, "hi": s.hi, "height": s.H, "kit_height": round( s.wall_h, 1 ), "scale": round( s.scale, 3 ),
		"t0": s.t0, "t1": s.t1, "walls": { k: v[0] for k, v in s.runs.items() }, "doors": { k: v[1] for k, v in s.runs.items() },
	} for s in laid]
	with open( os.path.join( project, "MapSource", "corridors_debug.json" ), "w", newline="\n" ) as fh:
		json.dump( dbg, fh, indent=1 )
	ntris = sum( len( t ) for t in kit.tris.values() )
	print( f"NOTORIOUS corridors: {len( laid )} laid of {len( segs )} found, {ntris} kit triangles in {len( names )} chunks, "
		f"{sum( len( b ) for b in kit.boxes.values() )} collision boxes, {stats['hidden']} map face parts cut, {stats['floor']} floor parts retextured, "
		f"{len( kit.lights )} lights" )
	return render, kit.lights
