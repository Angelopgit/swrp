"""
Rebuilds the Notorious corridors with the Venator corridor kit (X:\\SWRP Projects\\Corridor Prefab: VenatorPrefabV3.zip, a
modular Clone Wars corridor: wall panels, wall lights, pillars, ceiling light panels, door frames and bulkheads, PBR
textures). notorious_build.py calls apply() after it has gathered the map's faces and before the ceiling strips:

  1. Corridors are found on the holo-map's deck plan (64-unit floor cells): floor that is narrow one way (2-5 cells),
     long the other (8+ cells) and walled on both sides (rays against the map's collision brushes).
  2. For each straight corridor: its two wall planes, floor and ceiling are measured with rays, its ends are found by a ray
     down the middle, and each wall is walked in 4-unit steps to find where it really is (doorways and side openings are
     gaps; a gap with wall above it is a doorway).
  3. The kit is laid in: a bulkhead frame across the corridor every BULK_EVERY metres, standing on a pair of pillars;
     between them wall panels in a repeating pattern, stretched a little to fill each wall run exactly; a door frame
     lining every doorway, with a panel above it up to the ceiling; ceiling light panels wall to wall.
  4. The map's own faces there are restyled: the parts of wall and ceiling faces the kit covers are cut out (collision
     stays as it was), and the floor gets the kit's floor texture laid along the corridor.
  5. The kit goes out as its own chunk models (models/notorious/corridors), listed in Assets/data/notorious_corridors.json
     for notorious_scene.py; pillars, bulkheads and door frames get collision boxes. Ceiling light positions come back for
     the scene's point lights.

Scale: the kit's wall is 2.06 m floor to ceiling at 1:1. It is scaled to the corridor's height (1 unit = 1 inch; a clone is
72 units = 1.83 m) between MIN_SCALE and MAX_SCALE; a taller corridor gets the kit ceiling at the capped height.

The kit is a third-party asset kept local, like the map itself (see CLAUDE.md, IP and licence rules).
"""
