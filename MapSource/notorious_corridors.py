def clip( vs, nrm, d ):
	"""The part of a convex polygon where dot(nrm, p) >= d."""
	out = []
	n = len( vs )
	for i in range( n ):
		p, q = vs[i], vs[( i + 1 ) % n]
		dp = p[0] * nrm[0] + p[1] * nrm[1] + p[2] * nrm[2] - d
		dq = q[0] * nrm[0] + q[1] * nrm[1] + q[2] * nrm[2] - d
		if dp >= 0:
			out.append( p )
		if ( dp >= 0 ) != ( dq >= 0 ):
			k = dp / ( dp - dq )
			out.append( tuple( p[j] + ( q[j] - p[j] ) * k for j in range( 3 ) ) )
	return out if len( out ) >= 3 else []


def area( vs ):
	a = Vector( ( 0, 0, 0 ) )
	for i in range( 1, len( vs ) - 1 ):
		a += ( Vector( vs[i] ) - Vector( vs[0] ) ).cross( Vector( vs[i + 1] ) - Vector( vs[0] ) )
	return a.length / 2


def split( vs, planes ):
	"""(inside all planes, [outside pieces]); slivers under a square unit are dropped, so a cut never repeats."""
	outside = []
	cur = vs
	for ( nrm, d ) in planes:
		if not cur:
			break
		out = clip( cur, tuple( -x for x in nrm ), -( d - 0.05 ) )      # strictly outside: a face lying on the plane stays in
		if out and area( out ) >= 1.0:
			outside.append( out )
		cur = clip( cur, nrm, d )
	if cur and area( cur ) < 1.0:
		return [], [vs]
	return cur, outside


def restyle( render, segs ):
	"""Cut the map's faces where the kit stands; give the corridor floors the kit floor laid along the corridor."""
	index = collections.defaultdict( list )
	for s in segs:
		lo = s.A * ( s.t0 - 16 ) + s.C * ( s.lo - 16 )
		hi = s.A * ( s.t1 + 16 ) + s.C * ( s.hi + 16 )
		for gx in range( int( min( lo.x, hi.x ) // 512 ), int( max( lo.x, hi.x ) // 512 ) + 1 ):
			for gy in range( int( min( lo.y, hi.y ) // 512 ), int( max( lo.y, hi.y ) // 512 ) + 1 ):
				index[( gx, gy )].append( s )
	floor_mat = f"{MAT_DIR_REL}/floor.vmat"
	out = []
	stats = collections.Counter()
	queue = [( f, 0 ) for f in render]
	steps = 0
	while queue:
		steps += 1
		if steps % 20000 == 0:
			log( f"restyle: {steps} steps, {len( queue )} queued, {len( out )} out, {dict( stats )}" )
		f, start = queue.pop()
		mat, vs, n, scale = f
		if isinstance( scale, tuple ):           # model-UV faces can't be cut; leave them be
			out.append( f )
			continue
		zs = [p[2] for p in vs]
		segs_here = set()
		for p in vs:
			segs_here.update( index.get( ( int( p[0] // 512 ), int( p[1] // 512 ) ), () ) )
		done = False
		for s in sorted( segs_here, key=id ):
			if min( zs ) > s.z + s.H + 4 or max( zs ) < s.z - 4:
				continue
			A, C = tuple( s.A ), tuple( s.C )
			nA = tuple( -x for x in A )
			nC = tuple( -x for x in C )
			is_floor = n[2] > 0.95 and all( abs( z - s.z ) <= 3 for z in zs )
			if is_floor:
				planes = [( A, s.t0 ), ( nA, -s.t1 ), ( C, s.lo ), ( nC, -s.hi )]
			else:
				planes = [( A, s.t0 ), ( nA, -s.t1 ), ( C, s.lo - 2 ), ( nC, -( s.hi + 2 ) ), ( ( 0, 0, 1 ), s.z - 2 ), ( ( 0, 0, -1 ), -( s.z + s.H + 4 ) )]
			inside, outside = split( vs, planes )
			if not inside:
				continue
			loc = [( Vector( p ).dot( s.A ), Vector( p ).dot( s.C ), p[2] - s.z ) for p in inside]
			ups = [u for ( _, _, u ) in loc]
			acr = [c for ( _, c, _ ) in loc]
			if is_floor:
				T = KIT_WIDTH * s.scale * M
				mid = ( s.lo + s.hi ) / 2
				uvs = [( a / T, -( ( c - mid ) / T + 0.5 ) ) for ( a, c, _ ) in loc]
				out.append( ( floor_mat, inside, n, ( "uv", uvs ) ) )
				stats["floor"] += 1
			elif min( ups ) >= -2 and max( ups ) <= s.H + 4 and max( ups ) >= 1 and (
					all( c <= s.lo + SLAB for c in acr ) or all( c >= s.hi - SLAB for c in acr ) or all( u >= s.wall_h - SLAB for u in ups ) ):
				stats["hidden"] += 1
			else:
				continue
			if start > 12:
				if stats["looping"] < 3:
					log( f"restyle loop: face {vs} seg z {s.z} t {s.t0}..{s.t1} c {s.lo}..{s.hi} inside {inside} outside {outside}" )
				stats["looping"] += 1
				out.append( f )
				done = True
				break
			for piece in outside:
				queue.append( ( ( mat, piece, n, scale ), start + 1 ) )
			done = True
			break
		if not done:
			out.append( f )
	return out, stats


