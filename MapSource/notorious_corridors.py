def make_bvh( phys ):
	verts, polys = [], []
	for ( _, vs, _, _ ) in phys:
		i = len( verts )
		verts += [tuple( v ) for v in vs]
		polys.append( list( range( i, i + len( vs ) ) ) )
	return BVHTree.FromPolygons( verts, polys, all_triangles=False, epsilon=0.0 )


def ray( bvh, o, d, dist ):
	hit = bvh.ray_cast( Vector( o ), Vector( d ), dist )
	if hit[0] is None:
		return None
	return hit[3], hit[1]


def cells_by_level( rects ):
	levels = collections.defaultdict( set )
	for r in rects:
		for x in range( int( round( r[0] / CELL ) ), int( round( r[2] / CELL ) ) ):
			for y in range( int( round( r[1] / CELL ) ), int( round( r[3] / CELL ) ) ):
				levels[r[4]].add( ( x, y ) )
	return levels


def runs( occ ):
	rx, ry = {}, {}
	for ( x, y ) in occ:
		if ( x - 1, y ) not in occ:
			n = 0
			while ( x + n, y ) in occ:
				n += 1
			for i in range( n ):
				rx[( x + i, y )] = n
		if ( x, y - 1 ) not in occ:
			n = 0
			while ( x, y + n ) in occ:
				n += 1
			for i in range( n ):
				ry[( x, y + i )] = n
	return rx, ry


class Segment:
	def frame( self, t, c, h ):
		return self.A * t + self.C * c + Vector( ( 0, 0, self.z + h ) )


def find_segments( rects, bvh ):
	segs = []
	for z, occ in cells_by_level( rects ).items():
		if len( occ ) < 16:
			continue
		rx, ry = runs( occ )
		corr = {}
		for c in occ:
			a, b = rx[c], ry[c]
			if 2 <= min( a, b ) <= 5 and max( a, b ) >= 8:
				corr[c] = 0 if a > b else 1          # 0: runs along x, 1: along y
		seen = set()
		for c0, ax in corr.items():
			if c0 in seen:
				continue
			comp, stack = [], [c0]
			seen.add( c0 )
			while stack:
				c = stack.pop()
				comp.append( c )
				for d in ( ( 1, 0 ), ( -1, 0 ), ( 0, 1 ), ( 0, -1 ) ):
					n = ( c[0] + d[0], c[1] + d[1] )
					if n in corr and n not in seen and corr[n] == ax:
						seen.add( n )
						stack.append( n )
			if len( comp ) >= 12:
				s = measure( comp, ax, z, bvh )
				if s:
					segs.append( s )
	return segs


def measure( comp, ax, z, bvh ):
	"""Wall planes, ceiling and ends of one straight corridor; None if it isn't walled on both sides."""
	al = [c[ax] for c in comp]
	cr = [c[1 - ax] for c in comp]
	a0, a1 = min( al ) * CELL, ( max( al ) + 1 ) * CELL
	c_mid = ( min( cr ) + max( cr ) + 1 ) * CELL / 2
	width_guess = ( max( cr ) - min( cr ) + 1 ) * CELL
	s = Segment()
	s.ax, s.z = ax, z
	s.A = Vector( ( 1, 0, 0 ) ) if ax == 0 else Vector( ( 0, 1, 0 ) )
	s.C = Vector( ( 0, 1, 0 ) ) if ax == 0 else Vector( ( 1, 0, 0 ) )
	lo_hits, hi_hits, ceil_hits, floor_hits = collections.Counter(), collections.Counter(), collections.Counter(), collections.Counter()
	n = 0
	t = a0 + 16
	while t < a1 - 8:
		o = s.frame( t, c_mid, 40 )
		n += 1
		for sign, store in ( ( -1, lo_hits ), ( 1, hi_hits ) ):
			h = ray( bvh, o, s.C * sign, width_guess + 96 )
			if h and abs( h[1].dot( s.C ) ) > 0.95:
				store[round( c_mid + sign * h[0] )] += 1
		h = ray( bvh, o, UP, 1200 )
		if h and h[1].z < -0.95:
			ceil_hits[round( z + 40 + h[0] )] += 1          # absolute heights: the deck plan's floor z is snapped to 16
		h = ray( bvh, o, -UP, 120 )
		if h and h[1].z > 0.95:
			floor_hits[round( z + 40 - h[0] )] += 1
		t += 32
	if not lo_hits or not hi_hits or not ceil_hits or not floor_hits:
		return None
	s.z = z = float( floor_hits.most_common( 1 )[0][0] )
	lo, nlo = lo_hits.most_common( 1 )[0]
	hi, nhi = hi_hits.most_common( 1 )[0]
	H = ceil_hits.most_common( 1 )[0][0] - z
	if nlo < n * 0.35 or nhi < n * 0.35 or not 72 <= hi - lo <= 420 or H < 100:
		return None
	s.lo, s.hi, s.H = float( lo ), float( hi ), float( H )
	mid = ( s.lo + s.hi ) / 2
	# the corridor's ends: walls across it, seen from the middle (else a bit past its cells)
	tm = ( a0 + a1 ) / 2
	s.end0, s.end1 = a0 - 48, a1 + 48
	for sign in ( -1, 1 ):
		hits = [ray( bvh, s.frame( tm, mid + off, 40 ), s.A * sign, ( a1 - a0 ) / 2 + 48 ) for off in ( -( s.hi - s.lo ) * 0.3, 0, ( s.hi - s.lo ) * 0.3 )]
		d = [h[0] for h in hits if h and abs( h[1].dot( s.A ) ) > 0.9]
		if len( d ) == 3:
			if sign < 0:
				s.end0 = tm - min( d )
			else:
				s.end1 = tm + min( d )
	s.scale = max( MIN_SCALE, min( MAX_SCALE, H / ( KIT_WALL_H * M ) ) )
	s.wall_h = min( KIT_WALL_H * M * s.scale, H - KIT_TROUGH * M * s.scale - 4 )
	s.scale = min( s.scale, s.wall_h / ( KIT_WALL_H * M ) )
	return s


def wall_runs( s, bvh ):
	"""Per side: wall runs [(start, end)] and doorways [(start, end, top)] along the corridor."""
	out = {}
	mid = ( s.lo + s.hi ) / 2
	half = ( s.hi - s.lo ) / 2
	for side, sign in ( ( "lo", -1 ), ( "hi", 1 ) ):
		def present( t, h ):
			r = ray( bvh, s.frame( t, mid, h ), s.C * sign, half + 24 )
			return bool( r ) and abs( r[0] - half ) <= 5 and abs( r[1].dot( s.C ) ) > 0.9

		samples = []
		t = s.end0 + 1
		while t <= s.end1 - 1:
			samples.append( ( t, present( t, 40 ), present( t, s.wall_h - 10 ) ) )
			t += STEP
		walls, doors = [], []
		i = 0
		while i < len( samples ):
			low, high = samples[i][1], samples[i][2]
			j = i
			while j < len( samples ) and samples[j][1] == low:
				j += 1
			a = samples[i][0] - STEP / 2 if i else s.end0
			b = samples[j - 1][0] + STEP / 2 if j < len( samples ) else s.end1
			if low:
				if b - a >= 20:
					walls.append( [a, b] )
			elif i and j < len( samples ) and 40 <= b - a <= 160 and all( samples[k][2] for k in range( i, j ) ):
				top = 40.0
				c = ( a + b ) / 2
				while top < s.wall_h - 10 and not present( c, top ):
					top += 4
				if top >= 72:
					doors.append( ( a, b, top ) )
			i = j
		out[side] = ( walls, doors )
	return out


